//  localStorage 가 없는 브라우저(= 링크를 받은 **모든 고객**)에서 열면, 수식이 없으니
//  isPriceOn 이 거짓이 되어 mode "cost" 로 접히고 **「345 원」이 그대로 그려졌다**
