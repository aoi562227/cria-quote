const CFG_KEY = "cria-quote.showprice.v1";

/** 이 브라우저에 적어둔다. 실패는 무해하다 — 관리자 패널이 지금 값을 그대로 보여준다. */
export function savePriceCfg(cfg) {
  try {
    localStorage.setItem(CFG_KEY, JSON.stringify({
      cur: String(cfg?.cur ?? "auto"),
      KRW: String(cfg?.KRW ?? ""), JPY: String(cfg?.JPY ?? ""),
    }));
  } catch { /* 사생활 보호 모드 등 — 이번 세션에만 살고 만다 */ }
}

/** 적어둔 설정. 없거나 못 읽으면 **미설정**(= 종전 동작 = 원가 원화).
 *  ⚠ 여기서 「—」로 막으면 안 된다. 못 읽었다는 것은 「수식이 거부됐다」가 아니라
 *    「아직 아무 수식도 없다」이고, 그 상태에서 화면을 통째로 막으면 부스에서
 *    관리자 패널을 열기 전까지 아무 값도 못 보여준다(= 화면이 벽돌이 된다). */
export function loadPriceCfg() {
  try {
    const r = JSON.parse(localStorage.getItem(CFG_KEY) || "null");
    if (!r || typeof r !== "object") return { ...EMPTY_PRICE_CFG };
    const cur = r.cur === "KRW" || r.cur === "JPY" ? r.cur : "auto";
    return { cur, KRW: String(r.KRW ?? ""), JPY: String(r.JPY ?? "") };
  } catch { return { ...EMPTY_PRICE_CFG }; }
}

