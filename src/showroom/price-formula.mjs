// ══════════════════════════════════════════════════════════════════
//  ① 토크나이저
// ══════════════════════════════════════════════════════════════════
//  받는 것: 숫자(소수 포함) · `+ - * / ( )` · 식별자 `x`/`원가` · `rate`/`환율`.
//  공백은 버린다.
//  ⚠ 「모르는 글자는 조용히 버린다」로 하면 안 된다 — `*1.7원/10` 이 `*1.7/10` 으로
//    조용히 통과하면 관리자는 자기가 친 것이 그대로 쓰인다고 믿는다. 거부하고 **어느
//    글자인지** 말한다.
const IDENT = /^[A-Za-z_가-힣][A-Za-z0-9_가-힣]*/;
const OPS = "+-*/()";

/** 원가를 가리키는 이름들. */
const COST_NAMES = ["x", "X", "원가"];
/** 환율을 가리키는 이름들 = **1엔이 몇 원인가**(원/엔). 종전 `*1.7/10` 의 10 자리.
 *  ⚠ 운영자가 한국인이라 **한국어 이름이 본명**이고 `rate` 가 별칭이다. 둘뿐이다 —
 *    이름을 늘리면 부스에서 「어느 게 맞더라」가 되고, 그 물음의 답이 화면의 금액이다.
 *  ⚠ 이름을 **바꾸지 마라.** 이미 저장된 수식이 「모르는 이름」으로 거부된다. */
const RATE_NAMES = ["환율", "rate"];
/** 오타났을 때 화면에 그대로 나가는 한 줄 — 쓸 수 있는 이름을 **전부** 적는다. */
const NAMES_NOTE = `${COST_NAMES.join(" · ")} · ${RATE_NAMES.join(" · ")}`;

// ── 全角(전각) 정규화 — **일본 전시회 노트북의 IME 가 실제로 내는 글자다** ──────
//  실측: 日本語 IME 가 전각 모드일 때 `*1.7/10` 을 치면 `＊1.7／10` 이 들어온다.
//  종전에는 그대로 거부했고 메시지가 「쓸 수 없는 글자입니다 — «＊»」였다 —
//  11.5px 에서 ＊ 와 * 는 **구별되지 않는다.** 거부는 안전했지만(고객 화면은 「—」)
//  부스에서 그 메시지를 읽고 고칠 수가 없었다. 거부의 안전함은 고칠 수 있을 때만 뜻이 있다.
//
//  ⚠ 「모르는 글자를 조용히 버린다」와 다르다. 여기서 하는 것은 **같은 글자의 다른 표기**를
//    하나로 모으는 것이고(＊ 와 * 는 사용자에게 같은 뜻이다), 뜻이 바뀌는 변환은 없다.
//    모르는 글자는 여전히 거부한다 — 다만 **코드포인트를 같이** 말한다(보이지 않는
//    글자가 있다: 붙여넣기로 들어온 제로폭 공백은 «» 로 보여 꺾쇠 사이가 비어 있었다).
const FW_EXTRA = {
  "　": " ",   // 전각 공백
  "ー": "-",   // 長音符 ー — 전각 모드에서 「-」 키가 내는 글자다
  "−": "-",   // 수학 마이너스 −
  "×": "*",   // ×
  "÷": "/",   // ÷
};
/** 전각 ASCII 영역(U+FF01~FF5E)은 0xFEE0 을 빼면 그대로 반각이 된다. */
function normalizeSrc(s) {
  let out = "";
  for (const ch of String(s)) {
    const cp = ch.codePointAt(0);
    if (cp >= 0xFF01 && cp <= 0xFF5E) out += String.fromCharCode(cp - 0xFEE0);
    else out += (FW_EXTRA[ch] ?? ch);
  }
  return out;
}
/** 안 보이는 글자를 이름으로 말한다 — 「«»」만 뜨면 운영자가 고칠 수가 없다. */
const charName = c => {
  const cp = c.codePointAt(0);
  const u = `U+${cp.toString(16).toUpperCase().padStart(4, "0")}`;
  if (cp === 0x200B || cp === 0x200C || cp === 0x200D || cp === 0xFEFF)
    return `${u} 보이지 않는 글자 · 붙여넣기 대신 손으로 치세요`;
  return u;
};

function tokenize(src) {
  const s = String(src);
  const toks = [];
  let i = 0;
  while (i < s.length) {
    const c = s[i];
    if (c === " " || c === "\t") { i++; continue; }          // 공백 무시
    if ((c >= "0" && c <= "9") || c === ".") {
      let j = i, dots = 0;
      while (j < s.length && (((s[j] >= "0" && s[j] <= "9")) || s[j] === ".")) {
        if (s[j] === ".") dots++;
        j++;
      }
      const raw = s.slice(i, j);
      if (dots > 1) return { err: `숫자에 소수점이 둘 이상입니다 — «${raw}»` };
      if (raw === ".") return { err: "소수점만 있는 수는 읽을 수 없습니다" };
      const v = Number(raw);
      if (!Number.isFinite(v)) return { err: `숫자로 읽을 수 없습니다 — «${raw}»` };
      if (v > MAX_LIT) return { err: `숫자가 너무 큽니다 — «${raw}»` };
      toks.push({ t: "num", v });
      i = j; continue;
    }
    if (OPS.indexOf(c) >= 0) { toks.push({ t: c }); i++; continue; }
    const m = IDENT.exec(s.slice(i));
    if (m) {
      const w = m[0];
      // 우리가 줄 값은 **둘뿐**이다 — 원가와 환율. 다른 이름은 「나중에 값이 붙겠지」가
      // 아니라 **지금 틀린 것**이다.
      if (COST_NAMES.indexOf(w) >= 0) toks.push({ t: "var" });
      else if (RATE_NAMES.indexOf(w) >= 0) toks.push({ t: "rate" });
      else return { err: `모르는 이름입니다 — «${w}» (쓸 수 있는 것은 ${NAMES_NOTE} 뿐)` };
      i += w.length; continue;
    }
    return { err: `쓸 수 없는 글자입니다 — «${c}» (${charName(c)})` };
  }
  return { toks };
}

// ══════════════════════════════════════════════════════════════════
//  ② 접두 연산자 사슬 — 앞에 피연산자가 없으면 **원가**가 암묵 좌변이다
// ══════════════════════════════════════════════════════════════════
//  사용자가 실제로 치는 형태가 이것이다: `*1.7/10` · `(*1.7/10)` · `/10` · `+500`.
//  괄호로 감싼 형태까지 받아야 해서 **선행 `(` 를 건너뛴 자리**에 x 를 끼운다:
//    `(*1.7/10)` → `(` `*` … ⟹ `(` **x** `*` … = `(x*1.7/10)`
//  ⚠ 선행 `-` 도 같은 규칙을 탄다 = `-500` 은 「원가 − 500」이다. 「음수 500」이
//    아니다. 이 화면에서 상수 음수는 뜻이 없고(결과 음수는 어차피 거부다),
//    네 연산자를 다르게 대우하면 그 예외를 관리자가 외워야 한다.
function implyCost(toks) {
  let k = 0;
  while (k < toks.length && toks[k].t === "(") k++;
  if (k < toks.length && "+-*/".indexOf(toks[k].t) >= 0) toks.splice(k, 0, { t: "var" });
  return toks;
}

// ══════════════════════════════════════════════════════════════════
//  ③ 재귀하강 파서 — 좌결합, `* /` 가 `+ -` 보다 먼저
// ══════════════════════════════════════════════════════════════════
//    expr    := term  (('+'|'-') term)*
//    term    := factor (('*'|'/') factor)*
//    factor  := ('-'|'+')? primary            ← 괄호 안의 진짜 단항 부호
//    primary := num | var | rate | '(' expr ')'
//  ⚠ rate 는 var 와 **문법적으로 같은 자리**다(둘 다 잎이다). 그래서 이 절에 새 규칙이
//    없고, 우선순위·결합도 안 건드렸다 — 하위호환이 문법 차원에서 성립하는 이유다.
function parse(toks) {
  let p = 0, depth = 0;
  let err = "";
  const peek = () => toks[p];
  const bad = why => { if (!err) err = why; return { n: "num", v: 0 }; };

  const primary = () => {
    const tk = peek();
    if (!tk) return bad("수식이 도중에 끝났습니다");
    if (tk.t === "num") { p++; return { n: "num", v: tk.v }; }
    if (tk.t === "var") { p++; return { n: "var" }; }
    if (tk.t === "rate") { p++; return { n: "rate" }; }
    if (tk.t === "(") {
      if (++depth > MAX_DEPTH) return bad(`괄호가 너무 깊습니다 (최대 ${MAX_DEPTH}겹)`);
      p++;
      const inner = expr();
      if (err) return inner;
      if (!peek() || peek().t !== ")") return bad("여는 괄호에 닫는 괄호가 없습니다");
      p++; depth--;
      return inner;
    }
    if (tk.t === ")") return bad("괄호 안이 비어 있거나 값이 빠졌습니다");
    return bad(`연산자 «${tk.t}» 앞에 값이 없습니다`);
  };

  const factor = () => {
    const tk = peek();
    if (tk && (tk.t === "-" || tk.t === "+")) {
      p++;
      const a = factor();
      return tk.t === "-" ? { n: "neg", a } : a;
    }
    return primary();
  };

  const term = () => {
    let a = factor();
    while (!err && peek() && (peek().t === "*" || peek().t === "/")) {
      const o = toks[p++].t;
      a = { n: "op", o, a, b: factor() };
    }
    return a;
  };

  function expr() {
    let a = term();
    while (!err && peek() && (peek().t === "+" || peek().t === "-")) {
      const o = toks[p++].t;
      a = { n: "op", o, a, b: term() };
    }
    return a;
  }

  const node = expr();
  if (err) return { ok: false, why: err };
  // 남은 토큰이 있으면 「읽다 말았다」는 뜻이다 — 조용히 앞부분만 쓰면 안 된다.
  if (p < toks.length) {
    const tk = toks[p];
    const nm = tk.t === "num" ? tk.v : tk.t === "var" ? "원가" : tk.t === "rate" ? "환율" : tk.t;
    return { ok: false, why: `«${nm}» 앞에서 수식이 어긋납니다` };
  }
  return { ok: true, node };
}

/**
 * 수식 문자열 → 트리. **원가 없이도** 문법을 판정한다(관리자가 배치 전에 쳐 넣는다).
 * @returns {{ok:true, node:object} | {ok:false, why:string}}  why 는 화면에 그대로 나가는 한 줄
 */
export function compileFormula(src) {
  const raw = String(src ?? "");
  if (!raw.trim()) return { ok: false, why: "수식이 비어 있습니다" };
  if (raw.length > MAX_SRC)
    return { ok: false, why: `수식이 너무 깁니다 (${raw.length}자 · 최대 ${MAX_SRC}자)` };
  // 전각→반각을 **먼저** 돌린다(위 normalizeSrc 주석 — 일본 IME 가 내는 글자다).
  // 길이 상한은 정규화 전 원문으로 잰다: 저장소·주소창에 실리는 것이 원문이다.
  const tk = tokenize(normalizeSrc(raw));
  if (tk.err) return { ok: false, why: tk.err };
  if (!tk.toks.length) return { ok: false, why: "수식이 비어 있습니다" };
  return parse(implyCost(tk.toks));
}

/**
 * ★ 이 트리가 **환율을 쓰는가.** 화면이 두 곳에서 이 답을 필요로 한다:
 *   ① 환율이 없을 때 이 수식을 거부해야 하는지 (안 쓰면 거부할 이유가 없다 — 하위호환)
 *   ② 고객 화면에 「환율 8.70 (기준일)」을 적어도 되는지. 수식이 `*1.7/10` 인데
 *      받아 온 환율을 적으면 **화면이 거짓말을 한다** — 그 10 은 환율이 아니다.
 */
export function usesRate(node) {
  if (!node || typeof node !== "object") return false;
  if (node.n === "rate") return true;
  return usesRate(node.a) || usesRate(node.b);
}

/** 트리 + 원가 (+ 환율) → 값. 거부 사유는 문자열로 돌려준다(예외를 던지지 않는다 —
 *  이 값은 렌더 중에 계산되고, 렌더에서 던지면 부스 화면이 통째로 하얘진다).
 *  ⚠ `rate` 는 **세 번째 인자**이고 기본값이 없다. 안 넘기면 환율을 쓰는 수식만
 *    거부되고, 안 쓰는 수식(=기존 수식 전부)은 **한 글자도 안 바뀐다.** 그 사실이
 *    종전 호출부(`evalFormula(c.node, cost)`)를 그대로 살려 두는 근거다. */
export function evalFormula(node, cost, rate) {
  let err = "";
  const go = n => {
    if (err) return 0;
    if (n.n === "num") return n.v;
    if (n.n === "var") {
      if (!Number.isFinite(cost)) { err = "원가가 아직 없습니다"; return 0; }
      return cost;
    }
    if (n.n === "rate") {
      // ★ 기본값을 두지 않는다. 「없으면 10 으로」는 화면이 **틀린 값을 조용히**
      //   내놓는 길이고, 이 기능이 막으려는 것이 바로 그것이다.
      if (!Number.isFinite(rate) || rate <= 0) {
        err = "환율이 아직 없습니다 (관리자 패널에서 「지금 갱신」 또는 수동 입력)";
        return 0;
      }
      return rate;
    }
    if (n.n === "neg") return -go(n.a);
    const a = go(n.a); const b = go(n.b);
    if (err) return 0;
    let r = 0;
    if (n.o === "+") r = a + b;
    else if (n.o === "-") r = a - b;
    else if (n.o === "*") r = a * b;
    else {
      if (b === 0) { err = "0 으로 나눌 수 없습니다"; return 0; }
      r = a / b;
    }
    if (!Number.isFinite(r)) { err = "계산 도중 수가 아니게 됐습니다 (무한대·NaN)"; return 0; }
    return r;
  };
  const raw = go(node);
  // ★ IEEE **음의 0** 을 여기서 없앤다. `*-0` · `*0*-1` · `*(0*-1)` 은 -0 을 만드는데
  //   `raw < 0` 은 **-0 < 0 === false** 라 음수 검사를 그냥 통과한다. 그 뒤가 나쁘다:
  //   Math.round(-0) === -0 이고 (-0).toLocaleString() === "-0" 이라 고객 화면에
  //   **「¥-0」**이 뜬다(브라우저 실측). 부호만 지우고 값 판정은 0 게이트에 맡긴다 —
  //   여기서 「음수」라고 거부하면 이유 문자열이 「결과가 음수입니다 (0)」이 되어
  //   운영자가 못 읽는다. 0 의 처리는 **한 곳**(resolve 의 ZERO GATE)이 갖는다.
  const v = Object.is(raw, -0) ? 0 : raw;
  if (err) return { ok: false, why: err };
  if (!Number.isFinite(v)) return { ok: false, why: "결과가 수가 아닙니다 (NaN·무한대)" };
  if (v < 0) return { ok: false, why: `결과가 음수입니다 (${v})` };
  if (v > MAX_VALUE) return { ok: false, why: `결과가 너무 큽니다 (${v})` };
  return { ok: true, v };
}

/** 한 방에 — 파서 단위시험이 이 문을 쓴다. */
export function applyFormula(src, cost, rate) {
  const c = compileFormula(src);
  if (!c.ok) return c;
  return evalFormula(c.node, cost, rate);
}

// ══════════════════════════════════════════════════════════════════
//  ④ 반올림과 표기 — **코드가 소유한다**(화면이 아니라)
// ══════════════════════════════════════════════════════════════════
//  화면이 각자 반올림하면 「관리자 패널 34.68 · 큰 숫자 35 · 다른 화면 34」가 된다.
//  관리자 패널은 이 규칙을 **글로 보여준다**(ROUND_NOTE) — 숨은 반올림은 부스에서
//  「왜 계산이 안 맞죠」가 된다.
export const ROUND_NOTE = {
  // 엔은 실무 최소 단위가 1엔이다(소수 엔으로 청구하지 않는다).
  JPY: "엔은 소수점을 반올림해 1엔 단위로 표시합니다 (34.68 → 35)",
  // 원은 도메인 개당단가와 **같은 규칙**이다 — quote.mjs summarize 가 round(floor 아님).
  KRW: "원은 소수점을 반올림해 1원 단위로 표시합니다 (개당단가와 같은 규칙)",
};

// ⚠ 지금은 두 통화가 **같은 규칙**(정수 반올림)이라 cur 를 안 쓴다. 그래도 인자로
//   받는다 — 「엔은 10엔 단위로」 같은 요구가 오면 고칠 자리가 여기 한 곳이어야 하고,
//   부르는 쪽이 통화를 넘기고 있어야 그 변경이 화면 코드를 안 건드린다.
export const roundFor = (cur, v) => Math.round(v);

/**
 * 표시 형식. JPY `¥1,234` · KRW `1,234원`.
 * ⚠ 「원」은 **unitKey 로** 돌려준다 — 큰 숫자 옆의 작은 글씨 자리이고, 일본어
 *   화면에서는 「ウォン」이 되어야 한다(사전은 showroom-core 의 T 가 소유한다).
 *   여기서 한국어 「원」을 문자열에 박으면 일본어 화면이 한국어를 말한다.
 * ⚠ toLocaleString 을 인자 없이 부른다 — **미설정 경로와 같은 함수**여야 한다
 *   (하위호환 게이트가 그 동일성을 잰다).
 */
export function formatMoney(cur, n) {
  const s = n.toLocaleString();
  return cur === "JPY" ? { main: `¥${s}`, unitKey: null } : { main: s, unitKey: "won" };
}

// ══════════════════════════════════════════════════════════════════
//  ⑤ 무엇을 보여줄지 — 고객 몫과 관리자 몫을 **여기서 가른다**
// ══════════════════════════════════════════════════════════════════
/** 수식이 하나라도 있으면 「켜진」 상태다. 켜졌으면 **원가로 돌아가지 않는다.** */
export const isPriceOn = cfg =>
  !!(String(cfg?.KRW ?? "").trim() || String(cfg?.JPY ?? "").trim());

/** 지금 쓸 통화. "auto" 면 언어를 따르되, 관리자가 고른 값이 언어를 이긴다. */
export const curOf = (cfg, lang) => {
  const c = cfg?.cur;
  if (c === "KRW" || c === "JPY") return c;
  return lang === "ja" ? "JPY" : "KRW";
};

/** 쓸 통화 하나를 고른다. **「자동」일 때만** 빈 수식을 보고 다른 통화로 넘어간다.
 *
 *  ⚠ 관리자가 통화를 **명시로 고른 경우에는 절대 안 넘어간다.** 고른 것을 우리가
 *    뒤집으면 화면이 왜 그 통화인지 아무도 모른다.
 *  왜 「자동」에는 넘김이 필요한가 — 실측한 함정이다: 기본값이 auto 이고 화면은
 *  한국어로 뜬다. 관리자가 엔화 칸에 **첫 글자 `*` 를 치는 순간** isPriceOn 이 켜지고,
 *  cur 는 아직 KRW 인데 원화 수식이 비어 있어 고객 화면이 「—」로 죽는다. 통화를
 *  바꾸거나 원화 수식을 채울 때까지 그대로다 — 기본값이 하필 그 함정이었다.
 *  넘어가도 **원가는 안 보인다**(수식으로 계산한 값이고 단위가 ¥ 로 붙는다). */
function pickCur(cfg, lang) {
  const want = curOf(cfg, lang);
  const has = k => !!String(cfg?.[k] ?? "").trim();
  if (has(want)) return { cur: want, fell: null };
  const other = want === "JPY" ? "KRW" : "JPY";
  const auto = cfg?.cur !== "KRW" && cfg?.cur !== "JPY";
  if (auto && has(other)) return { cur: other, fell: want };
  return { cur: want, fell: null };
}

/**
 * @param {object}  a
 * @param {boolean} a.hideCost ★ **링크가 「가격을 가림」 표시를 달고 왔다**(state.noCostOfHash).
 *   이 브라우저에 수식이 없어도 원가로 접히면 안 된다 — 그 링크를 만든 사람은
 *   원가를 감추고 있었다. 자세한 판단은 아래 ⑥ 저장 절의 「링크」 문단에 있다.
 * @param {?{v:?number, text:string, asOf:string}} a.fx 지금 쓸 환율(원/엔).
 *   ★ 이 파일은 환율을 **받아 오지 않는다.** 어디서 왔는지·언제 받았는지·낡았는지는
 *     전부 fx-rate.mjs 가 안다(그래서 여기 import 가 여전히 0줄이다 — 머리말의 계약).
 *     여기서 쓰는 것은 `v`(계산) 와 `text`·`asOf`(화면에 적을 말) 뿐이다.
 *   ⚠ null 이어도 **환율을 안 쓰는 수식은 아무 영향이 없다.** 하위호환의 자리다.
 */
function resolve({ perEA, up, cfg, lang, hideCost = false, fx = null }) {
  // 원가 = 도메인이 낸 개당단가. 배치 전(up 0)이면 원가 자체가 없다.
  const cost = up > 0 && Number.isFinite(perEA) ? perEA : null;
  if (!isPriceOn(cfg)) {
    // ★ 남의 브라우저에서 열린 「가격을 가린」 링크 — **원가로 접지 않는다.**
    //   접으면 이 기능이 막으려던 바로 그 화면(한국 원화 원가)이 고객에게 뜬다.
    if (hideCost) {
      return { mode: "hidden", cur: curOf(cfg, lang), main: "—", unitKey: null, cost, src: "",
               why: "이 주소는 「가격을 가림」 표시를 달고 왔습니다 — 이 브라우저에는 수식이 " +
                    "없어 금액을 「—」로 둡니다 (원가로 되돌아가지 않습니다).", value: null,
               fxShown: null, usesFx: false };
    }
    // ── 하위호환: 수식 미설정 = **종전 그대로** 원가를 원화로. 바이트 동일해야 한다.
    //  ⚠ 여기에 환율을 끼워 넣지 마라 — 수식이 없다는 것은 환산도 없다는 뜻이다.
    return { mode: "cost", cur: "KRW", main: cost != null ? cost.toLocaleString() : "—",
             unitKey: "won", cost, src: "", why: "", value: null,
             fxShown: null, usesFx: false };
  }
  const { cur, fell } = pickCur(cfg, lang);
  const src = String(cfg?.[cur] ?? "");
  const base = { cur, cost, src, fell, usesFx: false };
  const blocked = why => ({ ...base, mode: "blocked", main: "—", unitKey: null, why, value: null,
                            fxShown: null });
  // ★ 통화를 골랐는데 그 통화의 수식이 비었다 = **거부**다. 원가로 되돌아가면
  //   관리자가 감추기로 한 원가가 그대로 뜬다. (「자동」의 넘김은 pickCur 가 이미 했다.)
  if (!src.trim()) return blocked(`${cur} 수식이 비어 있습니다 (통화를 바꾸거나 수식을 넣으세요)`);
  const c = compileFormula(src);
  if (!c.ok) return blocked(c.why);
  // ★ 이 수식이 환율을 쓰는가 — **이 한 줄이 하위호환의 경첩**이다.
  //   거짓이면 아래 어디에서도 fx 를 안 읽는다 = 환율이 무엇이든 종전과 같은 값이 나온다.
  const usesFx = usesRate(c.node);
  const rate = fx && Number.isFinite(fx.v) ? fx.v : null;
  base.usesFx = usesFx;
  if (cost == null) return blocked("원가가 아직 없습니다 (판에 도면을 앉히면 계산됩니다)");
  const r = evalFormula(c.node, cost, rate);
  if (!r.ok) return blocked(r.why);
  const n = roundFor(cur, r.v);

  // ══ ★ ZERO GATE — 고객 화면에 0 을 띄우지 않는다 ═══════════════════
  //  **반올림 뒤**에 잰다. 정확값으로 재면 두 부류를 통째로 놓친다:
  //    · 반올림해서 0 이 되는 것 — `*0.001`(0.204 → ¥0) · `/1000000000` · `-203.6`
  //      · `/500` … 경계는 반열림 [0, 0.5) 이다(`/408` 은 정확히 0.5 라 ¥1 이 된다).
  //    · 원가가 작을 때 — 원가 1원의 `*0.4` 는 정확값 0.4 로 「0 이 아닌데」 ¥0 이 된다.
  //  즉 **화면에 뜰 값**으로 판정하는 것이 요점이다. 산술은 맞는데 화면이 틀리는 자리다.
  //
  //  `!(n > 0)` 하나로 셋을 다 막는다 — 0 · **-0**(위 evalFormula 에서 이미 0 이 됐다) ·
  //  NaN(비교가 거짓이라 걸린다). `n === 0` 이나 `n <= 0` 으로 쓰지 마라: 전자는 -0 을
  //  잡지만 NaN 을 놓치고, 후자는 NaN 을 놓친다.
  //
  //  거부이지 경고가 아니다. 부스에서 오타 하나(`*1.7/10` → `*0`)로 고객에게 **¥0** 을
  //  보여주는 것은 「싸게 불렀다」가 아니라 **그 자리에서 발주를 받을 수 없는 화면**이다.
  //  0 원짜리 단상자는 우리 사업에 존재하지 않으므로 거부해서 잃는 정상 사용이 없다.
  if (!(n > 0)) {
    return blocked(`표시가가 ${Object.is(n, -0) ? 0 : n} 이 됩니다 (정확값 ${r.v}) — ` +
                   "고객 화면에 0 을 띄우지 않습니다. 수식을 확인하세요.");
  }

  const f = formatMoney(cur, n);
  // 상한 쪽은 거부가 아니라 **경고**다(BAND 주석). shownPriceOf 가 안 싣는
  // 자리에 둔다 — 이 문장은 관리자 몫이고 고객 화면에 나가면 안 된다.
  const band = BAND[cur];
  const ratio = cost > 0 ? n / cost : null;
  const warn = band && ratio != null && (ratio < band[0] || ratio > band[1])
    ? `원가의 ${ratio < 1 ? `1/${(1 / ratio).toFixed(1)}` : `${ratio.toFixed(1)}배`}입니다 ` +
      `(원가 ${cost}원 → ${f.main}). ${cur} 의 상식 밴드는 ${band[0]}~${band[1]}배입니다 — ` +
      (cur === "JPY" && ratio > band[1] ? "환율을 안 나눈 것 아닙니까 (예: *1.7 → *1.7/10)."
       : ratio < band[0] ? "원가보다 낮습니다 — 손해를 보고 파는 값입니다."
       : "오타가 아닌지 확인하세요 — 이 화면으로 발주가 나갑니다.")
    : "";
  // ★ 고객 화면에 환율을 적어도 되는 경우는 **하나뿐**이다 — 이 수식이 실제로
  //   환율을 썼을 때. `*1.7/10` 에 대고 「환율 8.70 (2026-09-03 기준)」이라고 적으면
  //   그 10 은 환율이 아니므로 **화면이 거짓말을 한다**(그리고 고객은 검산한다).
  //   ⚠ 여기서 원가가 새지 않는다: 고객은 표시가와 환율을 알게 되지만 그 둘로는
  //     `원가×마진` 까지만 복원되고 마진을 모르면 원가가 안 나온다. 환율은 ECB·상용
  //     환율로 어차피 공개된 수다.
  const fxShown = usesFx && fx ? { rate: String(fx.text ?? ""), asOf: String(fx.asOf ?? "") } : null;
  return { ...base, mode: "value", main: f.main, unitKey: f.unitKey, why: "",
           value: n, exact: r.v, warn, fxShown };
}

/**
 * ★ **고객이 보는 것 전부.** 이 객체에 없는 것은 화면에 그리지 않는다.
 *
 * 원가·수식·거부 사유가 **여기서 빠져 있는 것이 요점**이다. 페이지가 금액 칸을
 * 이 결과만으로 그리면 「고객 화면 DOM 에 원가가 없다」를 한 곳에서 보증할 수 있고,
 * 그 보증을 테스트가 문자열로 잰다(verify-speclink §M 원가 유출 검사).
 * ⚠ mode "cost"(= 수식 미설정 · 링크에 가림 표시도 없음)일 때는 main 이 곧 원가다.
 *   그게 이 모드의 정의이고 종전 동작이다 — 아무도 아직 감추기로 하지 않은 상태.
 *   가림 표시를 달고 온 링크는 mode "hidden" 이고 그때는 main 이 「—」다.
 * ⚠ 여기에 필드를 늘리지 마라. `why`(거부 사유) · `cost` · `src`(수식) · `warn` 이
 *   이 객체에 없는 것이 안전 논증의 절반이다(나머지 절반은 페이지가 이 객체만
 *   그린다는 것 — verify-speclink §M ⑪ 소스 계약 · ⑫ 렌더 게이트).
 *
 * ★ 26-09-04 — 필드를 **하나** 늘렸다: `fx`. 늘리지 말라고 적어 둔 자리라서 이유를 남긴다.
 *   · 무엇인가 — `null` 이거나 `{rate:"8.70", asOf:"2026-09-03"}`. **환율과 기준일**이다.
 *   · 왜 고객 몫인가 — 고객이 보는 ¥ 가 어느 환율로 환산됐는지 화면이 말해야 한다.
 *     그 자리(참고견적 줄)는 이미 있었고 숫자만 비어 있었다.
 *   · 왜 유출이 아닌가 — 위 resolve 의 fxShown 주석에 적었다(마진을 모르면 원가가
 *     복원되지 않는다 · 환율은 애초에 공개된 수다).
 *   · ★ **수식이 환율을 실제로 쓸 때만** 채워진다. 안 그러면 화면이 거짓말을 한다.
 */
export function shownPriceOf(a) {
  const r = resolve(a);
  return { mode: r.mode, cur: r.cur, main: r.main, unitKey: r.unitKey, fx: r.fxShown ?? null };
}

/**
 * ★ **수량별 표시가** — 표의 각 칸도 큰 글씨와 **똑같은 규칙**을 탄다 (26-08-26).
 *
 * 왜 이 함수가 여기 있나 — 「1,000개면 얼마, 5,000개면 얼마」가 부스 대화의 본체라서
 * 이 표는 화면에서 **가장 여러 번 읽히는 숫자**다. 여기로 원가가 새면 큰 글씨 하나를
 * 가리려고 파서를 짠 것이 통째로 무의미해진다. 그래서 표를 그리는 쪽이 원가를 만지지
 * 않게 **여기서 shownPriceOf 를 통과시켜** 표시용 배열로 바꿔 돌려준다.
 *   · 원가·수식·거부 사유·경고가 반환 객체에 **없다** — shownPriceOf 와 같은 이유·같은 계약.
 *   · 한 칸이 거부되면 그 칸만 「—」다. 원가로 되돌아가는 칸은 없다.
 * ⚠ 여기서 반올림·통화·밴드를 다시 적지 마라. resolve 한 곳이 소유한다.
 *
 * ★★ 수식 미설정(mode "cost")이면 **빈 배열을 돌려준다 = 표를 안 그린다** (26-08-26 2차).
 *   종전에는 「그 모드의 정의대로」 표도 원가 원화로 그렸는데, 그 순간 고객 화면에 뜨는
 *   원가가 **1개 → 5개**가 된다. 브라우저 실측(localStorage 비움): 「4 up · 개당 204 원」에
 *   더해 「1,000개 531원 / 3,000개 237원 / 4,000개 204원 / 5,000개 196원 / 10,000개 167원」.
 *   1,000개 531원은 4,000개 204원의 **2.6배**다 — 단가 하나가 아니라 **고정비/변동비 구조
 *   (원가 곡선) 자체**를 고객에게 그려 보인다. §16 은 큰 글씨 **하나**를 가리려고 파서·
 *   0 차단·가림 비트까지 지은 기능인데, 그 기능이 꺼져 있을 때의 노출면이 5배가 되는 것은
 *   「미설정이면 종전대로」가 아니다 — **종전에는 표가 없었다.**
 *   ⟹ cost 모드에서는 종전의 노출면(큰 글씨 하나)을 그대로 유지한다. 화면 코드는 안 만진다
 *      (ShowroomPage 는 `qtyShown.length` 로만 표를 낸다).
 *   ⚠ 상대값(「1,000개 +160%」)으로 그리는 안은 **버렸다** — 가리려는 것이 곡선인데
 *      상대값이 곡선 그 자체다.
 *   ⚠ 부스에서 표가 필요하면 수식을 켜라. KRW 원가 그대로가 필요하면 `*1` 이면 된다
 *      (그때는 관리자가 「보여주기로」 명시로 조작한 것이다).
 *
 * @param {{qty:number, up:number, perEA:?number}[]} a.rows showroom-core.qtyRowsOf 결과
 */
export const shownRowsOf = ({ rows, cfg, lang, hideCost = false, fx = null }) => {
  const out = (rows || []).map(r => {
    // ⚠ 환율·기준일은 **칸마다 적지 않는다.** 다섯 칸이 같은 수식·같은 환율을 타므로
    //   다섯 번 적으면 같은 말이 다섯 번이고, 그 말은 이미 큰 글씨 밑 한 줄에 있다.
    const { fx: _drop, ...cell } = shownPriceOf({ perEA: r.perEA, up: r.up, cfg, lang, hideCost, fx });
    return { qty: r.qty, ...cell };
  });
  // 한 칸이라도 원가를 적을 상태면 표 전체를 접는다(원가 한 개도 표로 새면 안 된다).
  return out.some(r => r.mode === "cost") ? [] : out;
};

