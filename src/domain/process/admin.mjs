//       그러나 「전부」는 **거짓**이었다. 나머지가 열한 축 다르다: 지종 350ab↔295ab ·
//       평량 350↔295 · 판형 하4↔4×62 · 절수 4↔2 · 지대R 0.65↔1.3 · 지대단가 518,196↔318,438 ·
//       인쇄 서식 **판당 1×50,000↔도수당 4×14,000** · 코팅 60,000↔40,000 · 접착 15원↔20원 ·
//       합계 678,827↔817,969 · 개당 170↔204. 통제된 쌍이 아니므로 「결정적 반례」로 못 쓴다.
//       결론은 그대로 두고 **근거만 전수 분포로 갈아끼운다** — 아래가 그것이다.
//     채굴 853건 중 일반관리비가 읽힌 **172건**(그중 수량도 읽힌 것 148건):
//       · 수량 **16종 중 11종**이 같은 수량에 서로 다른 관리비를 갖는다. 4,000ea(n=9) 하나만 봐도
//         100,000 / 120,000 / 130,000 / 200,000 / 500,000 **다섯 값**이 공존한다.
//         2,000ea 는 9종 · 5,000ea 8종 · 10,000ea 6종이다. (단일값으로 남은 5종은 전부 n≤2 —
//         표본이 하나둘뿐이라 갈릴 기회가 없었던 것이지 함수라는 증거가 아니다.)
//       · 비율로도 안 풀린다 — 관리비/공정합계가 **3.6~77.5%(중앙 16.4%)** 로 흩어진다.
//       · ★ 결정적인 것은 **구간이 포개진다**는 것이다: 관리비 100,000 건(n=44)의 공정합계
//         221,931~1,381,646 이 130,000 건(n=12)의 395,122~1,291,835 를 **통째로 품는다.**
//         즉 공정합계(=수량이 만드는 모든 것의 합)를 알아도 100,000 과 130,000 을 못 가른다.
//     수량에서 파생되는 어떤 값(정미·공정R·총생산EA)도 이 둘을 가르지 못한다. 다른 후보축도
//     전부 죽었다 — 공정 라인 수 r=0.01 · 지대R r=−0.02(26년 0.63이나 50,000ea 에서
//     880,000원을 뱉는다).
//  ③ 격자탐색(기본액 4만~16만 13종 × 계수 2.5~15 10종 × 눈금 1만/2만/5만 × 반올림·내림·올림 = 1,170식)
//     에서 **소스코의 4,000ea → 130,000 을 내면서 10,000~50,000ea 를 안 무너뜨리는 식이 없다.**
//     (3,000→120,000 과 4,000→130,000 을 잇는 직선은 10,000ea 에서 190,000, 50,000ea 에서
//      590,000 을 뱉는다. 실측은 각각 150,000 · 350,000 이다.)
//     적중만 보면 눈금 50,000 짜리 식이 이기지만, 그건 1,000·2,000 구간을 100,000 으로
//     눕혀 버는 점수이고 4,000ea 에서 100,000(또는 150,000)을 내놓아 절대선을 더 깬다.
//  ⚠ 현행식의 **알려진 계통오차**: 1,000ea·2,000ea 에서 110,000 을 낸다. 접착 단상자
//     실측은 26-04 이후 1,000ea 9건 중 8건 · 2,000ea 5건 전부가 100,000 이다(+10,000 과다).
//     그런데 그 구간만 내리면 3,000ea(같은 창에서 9건 중 7건이 120,000)가 같이 깨진다 —
//     2,000→100,000 과 3,000→120,000 사이의 20,000원 계단을 선형식이 못 넘는다.
//     ⟹ **식으로는 못 고친다.** 화면의 직접입력(adminManual)이 그 자리를 메우는 설계다.
//  ⟹ 식 유지. 고치려면 **인쇄·톰슨과 함께** 봐야 한다(print-prices.mjs 「답 3」의 상쇄 표) —
//    이 셋이 절대선(소스코 개당 204원)을 서로 상쇄로 지탱하고 있고, 26-09-13 에 셋을
//    동시에 회귀했지만 이 항목이 안 풀려 **하나도 움직이지 않았다.**
//
// ── ★ 26-09-15 「계단표로 갈아끼워라」 제안을 **기각한다** — R1·R5 를 안 지킨 수치였다 ──
//  백지 재설계(줄별회귀)가 「현행식은 중앙 −20% 싸게 부른다 · 147건 중 83건(56%)에서
//  싸다 · 계단표로 갈면 적중 21.8→42.3%」라며 수량 계단표를 제안했다. 같은 코퍼스를
//  **이 저장소의 표본 규칙으로 다시 세면 결론이 뒤집힌다:**
//     모수                      n    현행식 정확   중앙오차   우리가 싸게
//     전수(제안이 쓴 모수)       148    16.2%     −13.3%     55%
//     + R5 접착 단상자           110    19.1%       0.0%     45%
//     + R1 협상 1표              63    19.0%       0.0%     37%
//     + R2 26-04 이후 창          24    33.3%     **+9.1%**   **17%**
//  ⟹ 우리 물건(R5)만 남기고 협상을 1표로 세면(R1) **계통편향이 사라지고**, 현재 단가
//    창(R2)에서는 오히려 **비싼 쪽으로 9.1%** 서 있다. 「−20% 싸다」는 싸바리·쇼핑백·
//    카톤박스·의료기기세트를 같이 센 값이고(R5 위반), 한 협상을 3~6표로 센 값이다(R1 위반).
//    ⚠ 위 26-09-13 주석이 이미 「148건은 모수가 오염됐다」고 적어 뒀다 — 백지 재설계가
//      그 오염을 **다시 밟았다.** 규칙 R1·R5 는 바로 이걸 막으려고 세운 것이다.
//  ★ 제안의 두 계단을 각각 원문으로 되짚으면 근거가 무너진다:
//     · 「≤1,000 은 최빈 150,000 인데 우리는 110,000」 → R5+R1+R2 로 세면 1,000ea 는
//       100,000×5 · 150,000×1 로 **최빈이 100,000** 이다. 계단은 표본 오염이 만든 것이다.
//     · 「>30,000 은 최빈 600,000 인데 우리는 350,000」 → 그 600,000×3 은 **한 협상**
//       (40,000ea 한 건)을 세 번 센 것이다. R1 로 1표로 누르면 그 수량 구간은 n=1 이 된다.
//       같은 구간의 50,000ea 는 350,000 으로 현행식이 **정확히 맞는다.**
//  ⟹ 식 유지. 계단표는 **적중률만 보면 이기지만 그 적중은 오염된 표본에 맞춘 것**이고,
//    과적합은 다음 견적서에서 드러난다. 재량 항목이라는 결론(위 ①②③)은 그대로다.
//
// ── ★ 26-09-16 — **식을 또 안 고쳤다. 대신 모델을 고쳤다** ─────────────────────
//  선주 지시로 절대선 앵커를 실제 견적서 금액(소스코 817,969)으로 옮기면서 인쇄·톰슨·관리비
//  셋을 같이 맞춰야 했다. 관리비만 남았고, 여기서 갈림길이 둘이었다:
//    (가) 4,000ea → 130,000 을 내는 식을 만든다      ← **버렸다**
//    (나) 관리비는 재량값이라는 결론을 **모델에 반영한다** ← 이 길로 갔다
//  (가)를 버린 이유는 위 ②③ 이 이미 증명해 둔 것이다 — 격자탐색 1,170식 중 그 값을 내면서
//  10,000~50,000ea 를 안 무너뜨리는 식이 **없다**. 소스코만 맞는 식은 과적합이고, 그 대가는
//  이 저장소가 모르는 다음 견적서가 치른다. ✓ 26-09-16 독립 재계수로 전제를 다시 확인했다
//  (scratchpad/MY_recount.py): 관리비 읽힌 172라인 · 수량도 읽힌 148 · **수량 16종 중 11종이
//  같은 수량에 서로 다른 값**을 갖고, 4,000ea(n=9)는 100,000×4 · 120,000×1 · 130,000×2 ·
//  200,000×1 · 500,000×1 로 **다섯 값**이 공존한다. 수량은 이 값을 결정하지 않는다.
//
//  (나) 가 뜻하는 것 — **이 모듈의 역할 선언이 바뀐다.**
//    · calcAdmin 은 이제 「관리비를 계산하는 식」이 아니라 **기본값 제공자**다.
//      사용자가 아무것도 안 넣었을 때 화면을 빈칸으로 두지 않기 위한 출발점일 뿐이고,
//      그 값이 맞다고 주장하지 않는다(위 ②③ 이 맞을 수 없음을 보였다).
//    · 진짜 값이 들어오는 통로는 **ov.admin** 이다 — 화면의 「일반관리비 직접 입력」
//      (ui/state.mjs adminManual·admin → toQuoteInput → overrides.admin → 아래 lines).
//      이 통로는 종전부터 있었고 verify-total 26건이 전부 그 길로 실측을 주입한다.
//      26-09-16 에 새로 한 일은 통로를 만든 게 아니라 **절대선도 그 통로를 쓰게 한 것**이다.
//  ⚠ 그래서 절대선(verify-speclink §B)의 소스코 픽스처는 adminManual 로 **실측 130,000** 을 준다.
//    그 결과 §B 는 더 이상 calcAdmin 을 읽지 않는다 — calcAdmin 이 **감시자를 잃는다.**
//    ⟹ §B 에 calcAdmin 전용 검증점을 따로 박아 뒀다(아래 「검증」 줄의 5개 수량). 이 식을
//      고칠 때 빨개지는 자리는 이제 거기다. 감시 없는 상수를 만들지 않으려는 조치다.
export function calcAdmin(qty) {
  return Math.max(100000, Math.round((100000 + qty * 5) / 10000) * 10000);
}

export default {
  id: "admin",
  applies: () => true,
  lines: ctx => {
    const manual = ctx.ov?.admin;
    const amount = manual != null ? (manual || 100000) : calcAdmin(ctx.qty);
    return [{ id: "admin", name: "일반관리비",
              spec: manual != null ? "(직접입력)" : "자동",
              qty: "", unit: "", unitPrice: "", amount, fixed: true }];
  },
};
