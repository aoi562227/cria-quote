// ── 일반관리비 ────────────────────────────────────────────────────
// 100,000원 + 수량 × 5원, 1만원 단위 반올림, 최소 100,000
// 검증: 3,000→120,000 ✓ / 5,000→130,000 ✓ / 10,000→150,000 ✓
//       30,000→250,000 ✓ / 50,000→350,000 ✓   (실측 9건 중 7건 일치)
// ※ 코리팩가 재량으로 붙이는 항목이라 편차 있음 (같은 2,000ea에 100,000~200,000).
//   싸바리·G형처럼 공정이 많은 건은 실측이 더 높음 → 수동 입력으로 보정
//
// ── ★ 26-09-11 전수 채굴 — **식을 바꾸지 않았다.** 왜인지를 남긴다 ──────
//  견적서 529장에서 일반관리비와 수량이 같이 읽힌 건 148개. 현행식 적중 24/148 (16%).
//  낮아 보이지만 **더 나은 식이 없다** — 같은 수량에서 실측이 이렇게 흩어진다:
//     500ea   n=17 : 100,000×6  150,000×4  200,000×4  300,000×3
//     1,000ea n=39 : 100,000×19 130,000×2  150,000×8  180,000×1 200,000×7 250,000×2
//     2,000ea n=19 : 100,000×7 140,000×2 … 250,000×1 400,000×1   (같은 수량에 4배 편차)
//     5,000ea n=16 : 100,000×2 130,000×2 150,000×2 200,000×5 250,000×1 …
//  대안식 적중률도 전부 같은 자리다 — 내림 15% · 올림 18% · 100,000+반올림(수량×5) 16%.
//  ⟹ 관리비는 **수량만의 함수가 아니다.** 위 「재량」 주석이 데이터로 확인된 셈이다.
//  ⚠ 다만 최신 4건은 현행식보다 낮거나 같다 — 26-09-09 더치커피 2,000→100,000(식 110,000) ·
//    3,000→110,000(식 120,000) · 4,000→120,000 ✓ / 26-09-09 미구하라 10,000→150,000 ✓.
//    2,000·3,000 구간만 10,000원씩 높다. 고치려면 그 구간만 내리는 것이 아니라
//    **인쇄·톰슨과 함께** 봐야 한다(print-prices.mjs 「답 3」의 상쇄 설명) — 이 셋이
//    절대선(소스코 개당 204원)을 서로 상쇄로 지탱하고 있다.
export function calcAdmin(qty) {
  return Math.max(100000, Math.round((100000 + qty * 5) / 10000) * 10000);
}

export default {
  id: "admin",
  applies: () => true,
  lines: ctx => {
    const manual = ctx.ov?.admin;
    const amount = manual != null ? (manual || 100000) : calcAdmin(ctx.qty);
    return [{ id: "admin", name: "일반관리비",
              spec: manual != null ? "(직접입력)" : "자동",
              qty: "", unit: "", unitPrice: "", amount, fixed: true }];
  },
};
