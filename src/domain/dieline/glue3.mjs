import { GLUE_TAB, TIP_W } from "./geometry.mjs";

/**
 * 삼면접착 자동바닥(크래시록)
 *
 * 칼선 벡터 실측 3건으로 확정 (2026-08-04). 미지수 3개 · 3점 연립.
 *   웨이크버니A  W46  D46  H138  위띠 35.0  아래띠 61.0  netH 234.0
 *   웨이크버니B  W36  D36  H168  위띠 28.0  아래띠 51.0  netH 247.0
 *   소스코       W140 D43  H130  위띠 35.5  아래띠 57.9  netH 223.5
 * 소스코가 W≠D 라 처음으로 D·W 계수를 분리할 수 있었다.
 *
 *   위 띠  s = 0.67D + 0.03W + 2.8     3건 오차 0.31mm 이내
 *   아래 띠 b = D + 15                  3건 오차 0.1mm 이내
 *                                       (W 계수 −0.001 ≈ 0 — 폭은 무관)
 *   netH = H + s + b                    3건 오차 0.3mm 이내
 *
 * b = D + 15 는 물리적으로도 맞다 — 뚜껑이 깊이 D 를 덮고 15mm 혀가 더 나간다.
 * 종전 공식(0.88D+0.09W+20.6 / 0.33D+0.15W+11)은 bbox 만 보고 맞춘 회귀라
 * W 계수가 실제로는 없는데 있었고, 소스코에서 netH 를 23.4mm 크게 냈다.
 *
 * 큰 띠가 **아래**, 작은 띠가 **위**다. 종전에는 뒤바뀌어 있었고
 * 합이 비슷해 netH 로는 안 보였지만 빈 구멍 위치가 뒤집혀 맞물림이 통째로 틀렸다.
 * (몸통은 3건 모두 정확 — A 138.0 / B 168.0 / C 130.1 = H)
 */
export default {
  id: "glue_3side", label: "삼면접착", polygon: true,

  netSize(W, D, H, { hangTab = 0 } = {}) {
    const topLid   = 0.67 * D + 0.03 * W + 2.8;   // 작은 띠 (위)
    const botFloor = D + 15;                      // 큰 띠 = 뚜껑 (아래)
    return { netW: 2 * (W + D) + GLUE_TAB, netH: H + topLid + botFloor,
             topLid, botFloor, glueTab: GLUE_TAB, hangTab };
  },

  flaps(W, D, H) {
    const ns = this.netSize(W, D, H);
    // ── 자동바닥 날개 깊이 (웨이크버니 A·B y레벨 절단 실측) ─────────
    // 아래 날개대를 깊이별로 자르면 살아남는 구간이 줄어든다:
    //   0%   4구간 전부  /  15% 패널0 소멸  /  30% 3구간  /  50% 패널2 만
    // ⟹ 깊이 = [0.10b, 0.40b, b, 0.40b]
    //   패널0 은 15% 전에 끝나고, 패널1·3 은 30~50% 사이에 끝나고,
    //   패널2 만 밑바닥까지 내려간다.
    //
    // 왜 이 패턴이어야 맞물림이 성립하는가 (이론 검산)
    //   반전(rowAlt) 배치의 무겹침 조건은
    //       dy ≥ s + H + max_x[ bot(x) + bot_mirror(x) ] − b
    //   거울상은 깊은 패널2 를 다른 x 로 보내므로 합의 최대가 1.4b 가 되고
    //       겹침 = netH − dy = 0.6b
    //   삼면A 45.2 / 삼면B 68.6 / 웨이크버니B 30.7 / LUXEN 85.4mm
    //   필요 겹침 9.0 / 21.8 / 25.8 / 70.2mm 를 모두 덮는다.
    //   깊은 패널이 둘 붙어 있으면(종전 [0,0.36b,b,b]) 거울상과 항상 충돌해
    //   합의 최대가 2b 가 되고 겹침이 0 이 된다 — 그게 종전 실패 원인이었다.
    const b = ns.botFloor;
    return { type: "glue3", tipW: TIP_W,
      top: [ns.topLid, ns.topLid, ns.topLid, ns.topLid],
      bot: [b * 0.10, b * 0.40, b, b * 0.40] };
  },
};
