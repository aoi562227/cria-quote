import { GLUE_TAB } from "./geometry.mjs";

/**
 * 맞뚜껑 (상하 텍 클로저)
 *   상하 대칭. 한쪽 날개 = 전폭 뚜껑패널(D) + 좁은 텍 혀(16.5)
 *   netH = H + 2·(D + 16.5) = H + 2D + 33
 *
 * ① 뚜껑패널 = D 정확 — 칼선 PDF 2건이 세로 접는선의 y 범위로 직접 확인했다
 *    (아트워크에 오염되지 않는 측정법. verify-imposition.mjs ③ 참조)
 *      바이오머   150×15×150   몸통 성분 180.0 = H+2D  (y 31.66~211.66)
 *      더파이러츠 190×68×280   몸통 성분 416.0 = H+2D  (x 42.06~572.36)
 *    종전 주석의 「뚜껑 66.5 ≈ D−3(여유)」은 칼선-07 접는선 눈대중 판독이었고
 *    그 합이 320.0 ≠ 실측 321.0 이었다. 위 2건이 D 정확을 확정했으니 폐기한다.
 *
 * ② ★ 텍 혀는 상수가 아니다 — 목형마다 15.0~18.0 으로 흩어진다 (26-08-07 재조사)
 *    혀 = (netH실측 − (H+2D)) / 2 로 역산한 실측 4건 / 목형 3벌:
 *
 *      샘플        W×D×H          netH실측  몸통 H+2D   혀     근거 강도
 *      바이오머    150×15×150      210.0     180.0     15.00  PDF 성분 직접 실측
 *      더파이러츠  190×68×280      452.0     416.0     18.00  PDF 성분 직접 실측
 *      칼선-07     150×69.5×149    321.0     288.0     16.50  netH 만 실측 → 역산
 *      칼선-08     150×69.5×219    391.0     358.0     16.50  같은 목형족(D 동일)
 *
 *    혀 상수 후보별 netH 오차 (바이오머 / 더파이러츠 / 칼선-07 / 08):
 *      t=15.0   +0.0  −6.0  −3.0  −3.0   MAE 3.00mm
 *      t=16.5   +3.0  −3.0  ±0.0  ±0.0   MAE 1.50mm  ← 채택. 목형 3벌 평균과 정확히 일치
 *      t=18.0   +6.0  ±0.0  +3.0  +3.0   MAE 3.00mm
 *
 *    ★ 26-08-07 재실측 — 추출기를 직접 돌려 「세로 접는선 span」으로 다시 쟀다
 *      (verify-imposition ③ 과 같은 방법. 가로 크리스는 1mm 안쪽에 또 하나가 있어
 *       몸통을 414 로 오독한다 — 몸통은 반드시 세로 접는선으로 특정해라):
 *        바이오머   세로선 x=196.03·346.03  y 31.66~211.66 = 180.00 (=H+2D)
 *                   bbox y 16.66~226.66 = 210.00  → 혀 위 15.00 / 아래 15.00
 *        더파이러츠 세로선 x=315.06·505.06  y 30.96~446.96 = 416.00 (=H+2D)
 *                   bbox y 12.96~464.96 = 452.00  → 혀 위 18.00 / 아래 18.00
 *      위·아래 대칭 오차가 두 건 다 0.00 이다. 혀 15.0 vs 18.0 은 측정 잡음이 아니다.
 *
 *    ⚠ 순환 근거 주의 — `geometry.mjs:28-29` 의 「전체 213.0 / 449.0」 은 실측이 아니라
 *      **이 공식 H+2(D+16.5) 의 출력**이다. 같은 줄의 몸통(150.0/180.0 · 280.0/416.0)은
 *      진짜 실측이라 「전체」도 실측으로 읽히지만, 실측 netH 는 210.0 / 452.0 이고
 *      차이가 정확히 −3.0 / +3.0 — t=16.5 의 두 잔차 그 자체다. 그 줄로 16.5 를
 *      검증하면 공식이 공식을 확인하는 순환이 된다. 대조는 verify-pdf §A 오라클로 해라.
 *
 *    ⚠ 바이오머 netH 210.0(=혀 15.0)을 그대로 반영해 t=15.0 으로 바꾸면 오차가
 *      **2배가 된다.** 같은 추출기·같은 측정법의 더파이러츠가 18.0 이라 서로 상쇄되지
 *      않는다. 샘플 1건에 맞추는 것이므로 하지 마라 — 실행해서 확인했다(아래 ③).
 *    ⚠ D 의존으로도 설명이 안 된다. 목형 3벌 회귀는 혀 = 0.0413D + 14.40 (잔차 0.8mm)
 *      이지만, D 가 1.5mm 밖에 안 다른 더파이러츠(68→18.0)와 칼선-07(69.5→16.5)의
 *      국소 기울기가 **−1.00** 으로 부호가 반대다. 즉 D 기울기는 목형 산포(±1.5mm)에
 *      묻혀 있고 분리 불가다. 상수 유지가 정직한 선택이다.
 *
 * ③ A/B 실행 결과 (t=16.5 → 15.0, 11개 스위트 전부 실행)
 *    움직인 점수: **없다.** verify-net 판걸이 7/10 · 비폴리곤 6/6 · verify-total 24/26 ·
 *    verify-r 37/39 · verify-print 19/20 · scorecard2 10/15 · scorecard-nest 7/10 ·
 *    scorecard-unit 7/12 · verify-dieline 360/360+36/36 · verify-pdf 66/68 전부 동일.
 *    나빠진 것 1개: verify-net 맞뚜껑 세로 평균절대오차 **0.0mm → 3.0mm**.
 *    netH 가 3mm 줄어 맞뚜껑A 199→196 · B 223→220 이 되지만 up 은 6/6 · 2 그대로다.
 *    ⚠ verify-pdf 가 안 움직이는 것은 안전 신호가 아니다 — 그 스위트는 PDF 추출기를
 *      채점하고 이 공식을 읽지 않는다. 맞뚜껑 netH 의 유일한 점수판은 verify-net 이다.
 *    26-08-07 13개 스위트로 재실행해 위 결과를 그대로 재현했다. 추가로 확인된 것 1개:
 *    verify-interlock 은 맞뚜껑 2행의 「필요 겹침」 수치만 따라 움직이고(A 30→28 ·
 *    B 37→35) up 7/10 은 불변이다 — 점수가 아니라 파생 표시값이다.
 *
 * ④ 삼면접착 아래 띠 D+15 와 같은 규칙인가 — **구조는 같고 상수는 다르다**
 *    같은 것: 띠 = [전폭 패널 D] + [좁은 텍 혀] 라는 분해. 삼면접착도 PDF 성분이
 *      혀를 따로 떼어 낸다(소스코 몸통 208.5 + 혀 15.0 = 223.5, 아래 띠 57.9 ≈ D+15).
 *      ①에서 맞뚜껑 뚜껑패널이 D 정확으로 확인됐으므로 분해 자체는 우연이 아니다.
 *    다른 것: 혀 값. 삼면접착은 D 36~46 에서 3벌 전부 정확히 15.00 (산포 0) 인데
 *      맞뚜껑은 15.0~18.0 으로 흩어진다. 삼면접착 자동바닥 혀는 잠금 길이가 목형
 *      표준으로 고정된 값이고, 맞뚜껑 텍 혀는 아가리에 끼우는 마찰 길이라 설계자
 *      재량이 남는다 — 구조와 무관하다. 즉 바이오머의 15.0 이 삼면접착 15.0 과
 *      같은 것은 **값 수준에서는 우연**이다. 두 상수를 묶지 마라.
 *
 * ⑤ 폐기된 공식 (지우지 마라 — 「왜 이 공식이 아닌가」를 잃는다)
 *    D/2+20 / D/2+15 → 칼선-07/08 두 건 모두 −67.5mm 부족. 원본은 verify-net.mjs OLD.
 *    ✓ 맞뚜껑A 92×13×140 국2: 224×199 → 회전 3×2 = 6up (견적서 6up 일치)
 *      종전 공식(224×258)으로는 4up 밖에 안 나왔다.
 */
export default {
  id: "tuck_both", label: "맞뚜껑 (상하 텍 클로저)", polygon: true,

  netSize(W, D, H, { hangTab = 0 } = {}) {
    // 혀 16.5 는 목형 3벌 실측(15.0 / 16.5 / 18.0)의 평균이자 최소오차 상수다. 위 「②」 참조
    const topLid = D + 16.5, botFloor = D + 16.5;
    return { netW: 2 * (W + D) + GLUE_TAB, netH: H + topLid + botFloor,
             topLid, botFloor, glueTab: GLUE_TAB, hangTab };
  },

  flaps(W, D, H) {
    const ns = this.netSize(W, D, H);
    const dust = Math.min(0.43 * D + 7, ns.topLid * 0.85);   // 더스트는 뚜껑보다 낮다
    const bDust = Math.min(dust, ns.botFloor * 0.85);
    // 상단 뚜껑은 전면(1)에만, 하단 뚜껑은 후면(3)에만 — 뚜껑이 2개면 맞물림 불가
    return { type: "tuck", tipW: null,
      top: [dust, ns.topLid, dust, 0],
      bot: [bDust, 0, bDust, ns.botFloor] };
  },
};
