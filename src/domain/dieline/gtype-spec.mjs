/**
 * G형 (규격도) — 사용자가 그려 준 규격 도면 2장을 **패널 단위로 그대로** 옮긴 구조 (26-10-02)
 *
 *   전개도 가로 = W + 4H        전개도 세로 = 2D + 4H        (상수 없음 — 전 패널이 W·D·H 다)
 *
 *            ┌───────┐                     가운데 열(폭 W) 위→아래
 *            │ 꽂이 H │                       꽂이날개 H · 뚜껑 D · 뒷벽 H · 바닥 D · 앞벽 H · 앞벽 안날개 H
 *        ┌───┼───────┼───┐                 뚜껑 양옆   : 옆날개  H × D
 *        │날개│ 뚜껑 D │날개│                 뒷벽·앞벽 양옆: 모서리 사각 H × H
 *        ├───┼───────┼───┤                 바닥 양옆   : 옆벽 H × D + 바깥벽 H × D (이중벽)
 *        │모서│ 뒷벽 H │모서│
 *    ┌───┼───┼───────┼───┼───┐
 *    │바깥│옆벽│ 바닥 D │옆벽│바깥│
 *    └───┼───┼───────┼───┼───┘
 *        │모서│ 앞벽 H │모서│
 *        └───┼───────┼───┘
 *            │안날개 H│
 *            └───────┘
 *
 * 근거 — `docs/g형예시/` 의 두 PDF 를 사각형 16개씩 mm 로 읽어 대조했다(오차 ≤0.4mm · 손으로 맞댄 도면의 어긋남):
 *     G형예시.pdf    120×125×55 → 도면 340.0×469.9 / 식 340×470
 *     G형예시2.pdf   200×80×70  → 도면 480.0×440.0 / 식 480×440
 *   두 장 다 16패널 전부가 W·D·H 한 벌로 설명된다(test/verify-dieline 「규격 도면 대조」가 상시 감시).
 *
 * ⚠ 이 구조는 `gtype_tray`(G형 트레이 · 뚜껑일체)와 **모양이 같고 크기 식이 다르다.**
 *     gtype_tray : (W+4H+44.5) × (2D+3H+19.5) — 실제 칼선 4건의 bbox 회귀(여유분 포함 · 폴리곤 없음)
 *     이 구조     : (W+4H)      × (2D+4H)      — 규격 도면(여유분 없음 · 폴리곤 있음)
 *   200×80×70 이면 524.5×389.5 vs 480×440 이다. 어느 쪽이 실물인지는 **이 자료로 못 가른다** — 규격 도면은
 *   종이 두께·끼움 여유를 안 그린 도식이고, 실측 4건은 원본 PDF 가 소실돼 패널을 못 본다.
 *   그래서 기존 두 구조(gtype · gtype_tray)는 **한 칸도 안 건드리고** 이 구조를 따로 세웠다(사용자 「알아서」 26-10-02 —
 *   기존 값을 바꾸지 않는 쪽으로 골랐다). 실제 G형 칼선이 오면 그걸로 셋을 정리해라.
 *
 * ★ 26-10-02 판정 — **G형은 두 종류이고 이 구조는 「앞벽 두 겹형」이다.** 사용자가 준 영상 2개(실물 상자를 펼치는 장면)로 갈랐다:
 *     영상 143436612(빨강·흰 상자) — 앞벽 아래 한 칸이 더 있고 접어 넘겨 바닥 홈에 걸린다 = **이 규격도**(가운데 열 6칸 · 2D+4H)
 *     영상 142545450(분홍 상자)    — 앞벽 한 겹, 뚜껑 꽂이가 반달 홈에 끼워진다 = 모자 칼선·마스크 견적(5칸 · 2D+3H) → gtype_tray
 *   두 종류 모두 옆벽은 두 겹이고 **모서리 날개가 있다**(앞벽·뒷벽 양 끝). 종전 이 자리에 「모서리 사각이 실물에 없다」고
 *   적었는데 **틀렸다** — 마스크 견적서의 그림이 단순화돼 있었던 것이고, 모자 칼선에도 있다(왼벽 위·아래 칸 · 뒷벽 옆 사다리꼴).
 *   ⚠ 사용자 지시(26-10-02): 「사각형 그린 것보다 **실제 도면이 정식**」. 이 구조는 규격 도식이라 여유분이 없다 —
 *     앞벽 두 겹형의 실제 칼선이 오면 그 치수로 고쳐라. 그때까지 「앞벽 한 겹형」 견적은 gtype_tray 를 써라
 *     (마스크 270×370×70 을 여기에 넣으면 긴 축이 70 길어 46전지에 안 선다 — 구조가 다른 것이다).
 *
 * ⚠ 선 구분(칼선/접는선)은 **도면에 없다** — 색 사각형뿐이다. 그래서 folds 를 지어내지 않고
 *   패널 사각형 16개의 테두리를 전부 cuts 로 낸다(화면이 도면과 같은 그림이 된다). 배치에 쓰는 것은 윤곽뿐이다.
 */
import { rect } from "./geometry.mjs";

/** 패널 16개 — [이름, x0, y0, x1, y1] (mm · 좌상단 원점 · y 아래로). 그림·배치·검증이 전부 이것 하나를 읽는다. */
export function panels(W, D, H) {
  const xC0 = 2 * H, xC1 = 2 * H + W;                         // 가운데 열
  const y = [0, H, H + D, 2 * H + D, 2 * H + 2 * D, 3 * H + 2 * D, 4 * H + 2 * D];
  const side = (name, yi) => [                                 // 가운데 열 양옆 한 칸(폭 H)
    [name + "(좌)", xC0 - H, y[yi], xC0, y[yi + 1]],
    [name + "(우)", xC1, y[yi], xC1 + H, y[yi + 1]],
  ];
  return [
    ["꽂이날개", xC0, y[0], xC1, y[1]],
    ["뚜껑", xC0, y[1], xC1, y[2]], ...side("뚜껑 옆날개", 1),
    ["뒷벽", xC0, y[2], xC1, y[3]], ...side("모서리(뒤)", 2),
    ["바닥", xC0, y[3], xC1, y[4]], ...side("옆벽", 3),
    ["바깥벽(좌)", 0, y[3], H, y[4]], ["바깥벽(우)", xC1 + H, y[3], xC1 + 2 * H, y[4]],
    ["앞벽", xC0, y[4], xC1, y[5]], ...side("모서리(앞)", 4),
    ["앞벽 안날개", xC0, y[5], xC1, y[6]],
  ];
}

export default {
  id: "gtype_spec", label: "G형 (규격도 · 앞벽 두 겹)", labelJa: "G型（規格図・前壁二重）",
  tag: "G형규격",
  verified: "규격 도면 2건", polygon: true, thomsonDefault: "g_std",

  netSize(W, D, H, { hangTab = 0 } = {}) {
    return {
      netW: W + 4 * H, netH: 2 * D + 4 * H,
      topLid: 0, botFloor: 0, glueTab: 0, noRotate: false, hangTab,
      note: ["G형 (규격도 · 앞벽 두 겹)", "W+4H × 2D+4H · 여유분 없음"],
      warning: null,
    };
  },

  // 슬리브 위상(몸통4+접착탭)이 아니라 날개 프로파일이 없다. 계약(폴리곤 구조는 flaps 를 준다 ·
  // max(top)=topLid)을 지키기 위해 **0 짜리 프로파일**을 준다 — 도형은 아래 pieces() 가 만든다.
  flaps: () => ({ type: "panels", top: [0], bot: [0] }),

  /** 배치용 볼록 조각 5개(십자 겹침 없이 윤곽을 정확히 덮는다) + 그림용 패널 테두리. */
  pieces(W, D, H) {
    const ps = panels(W, D, H);
    const netH = 2 * D + 4 * H, xC0 = 2 * H, xC1 = 2 * H + W;
    const yB0 = 2 * H + D, yB1 = 2 * H + 2 * D;               // 바닥 줄
    const pieces = [
      rect(xC0, 0, xC1, netH),                                // 가운데 열 전체
      rect(xC0 - H, H, xC0, netH - H),                        // 왼쪽 안열(옆날개·모서리·옆벽·모서리)
      rect(xC1, H, xC1 + H, netH - H),                        // 오른쪽 안열
      rect(0, yB0, H, yB1),                                   // 왼쪽 바깥벽
      rect(xC1 + H, yB0, xC1 + 2 * H, yB1),                   // 오른쪽 바깥벽
    ];
    const meta = [
      { panel: 1, part: "body" }, { panel: 0, part: "wall" }, { panel: 2, part: "wall" },
      { panel: 4, part: "wall" }, { panel: 4, part: "wall" },
    ];
    const cuts = ps.map(([, x0, y0, x1, y1]) => [[x0, y0], [x1, y0], [x1, y1], [x0, y1], [x0, y0]]);
    return { pieces, meta, cuts, folds: [], panels: [] };
  },
};
