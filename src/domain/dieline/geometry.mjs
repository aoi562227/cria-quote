// ══════════════════════════════════════════════════════════════════
//  geometry.mjs — 전개도 폴리곤 생성 (치수와 그림의 단일 출처)
// ══════════════════════════════════════════════════════════════════
//
//  왜 이 파일이 있나
//  ────────────────
//  종전에는 전개도 '크기'(calcNetSize)와 '그림'(getFlaps)이 서로 다른
//  회귀식을 썼다. 출처가 다른 두 벌이 섞여 폴리곤이 netH 와 어긋났다.
//      맞뚜껑  netH = H + 2(D+16.5)  ↔  그려지는 높이 = H + 2·round(0.03D+10.6)
//               → 92×13×140 에서 199.0 vs 165.2  (−33.8mm)
//               → 150×69.5×149 에서 321.0 vs 222.8 (−98.2mm)
//      십자    netH = H + 2(7D/8+5.5) ↔  그려지는 높이 = H + (0.08D+9) + 0.7D
//               → 70×70×55 에서 188.5 vs 141.1  (−47.4mm)
//      삼면접착 만 우연히 일치했다.
//  NFP 배치는 폴리곤을 입력으로 쓰므로, 도형이 25~30% 작으면 실제로는
//  불가능한 배치를 가능하다고 판정한다. 십자B 가 4up 이 아니라 6up 으로
//  나온 원인이 이것이다(clearance 부족이 아니었다).
//
//  그래서 크기와 그림을 한 곳에서 만들고, 다음 불변식을 강제한다.
//      max(top) === netSize.topLid
//      max(bot) === netSize.botFloor
//      폴리곤 bbox === netW × netH        (오차 0)
//
//  ★ 날개는 2단 구조다 (칼선 실측)
//      [텍 혀  topLid − D]   ← 좁다. 상자 아가리로 들어가야 하므로 안쪽으로 물림
//      [뚜껑 패널  D    ]   ← 전폭. 윗면을 덮는 판
//      [몸통  H        ]
//    바이오머 150×15×150: 몸통 150.0 / 뚜껑패널 접는선까지 180.0(=H+2D) / 전체 213.0
//    더파이러츠 190×68×280: 몸통 280.0 / 416.0(=H+2D) / 전체 449.0
//    좁은 혀 옆의 빈 공간이 맞물림이 들어가는 유일한 자리다.
//    종전 모델은 topLid 전체를 전폭 사다리꼴 1개로 그려 이 공간을 없앴다.
// ══════════════════════════════════════════════════════════════════

// 전개도 가로 = 2(W + D) + 14.3
//   실제 발주 규격이 확인된 칼선 3건이 **전부 정확히 14.3** (오차 0.0):
//     삼면E   90×70 → 2(W+D)=320.0, 실측 334.3  → 14.3
//     칼선-06 50×50 → 200.0, 실측 214.3  → 14.3
//     칼선-05 47×47 → 188.0, 실측 202.3  → 14.3
//   (규격 미확인 칼선 4건은 12.5~24 로 흩어짐 — 패널 폭을 접는선에서 추정했기 때문)
//   회귀계수도 2.09·W + 1.86·D 로 2·2 수렴 확인.
//
// ★ 26-08-16 — 이 상수는 「접착탭 폭」이 **아니다.** 이름이 거짓말을 하고 있었다.
//   세로 크리스를 직접 재면(가정 없이 세로 선분 길이 누적, 길이 ≥ 0.6H)
//   접착탭은 6/6 전부 **정확히 15.00** 이고, 탭이 붙는 D 패널이 0.70mm 짧다.
//     웨이크A 46×46  [0, 15.00, 61.00, 107.00, 153.00, 198.30]
//     웨이크B 36×36  [0, 15.00, 51.00,  87.00, 123.00, 158.30]
//     도솔    50×50  [0, 15.00, 65.00, 115.00, 165.00, 214.30]   ← 6/6 경계 잔차 0.00mm
//   즉 netW = 2(W+D) + 14.3 은 「2W + (D−0.7) + D + 탭 15.0」이 우연히 같은 값이고,
//   **netW 자체는 손댈 이유가 없다** (14.3 + 0.7 = 15.0 이 자동으로 맞는다).
//   부수 발견: 0.70mm 는 날개 경계마다 0.70mm 떨어진 세로선 쌍(길이 7~12mm)으로도
//   나타난다 = 날개 사이 릴리프 슬릿. 현행 폴리곤에는 그 슬릿이 없어 도형이 그만큼
//   크다(= 안전측, 조치 불필요).
export const GLUE_TAB = 14.3;   // netW 가산분. 실제 탭 폭은 15.0 = GLUE_TAB + GLUE_TAB_SHORT
// 탭이 붙는 D 패널의 부족분. 위 크리스 실측 3건에서 6/6 경계 잔차 0.00mm.
export const GLUE_TAB_SHORT = 0.7;

// (TONGUE_INSET=6 은 삭제했다 — 「맞물림 깊이를 직접 결정한다」고 적혀 있었지만
//  실제로 그 역할을 하는 것은 아래 TAPER_MAX=10.2 다. 어떤 계산에도 쓰이지 않아
//  실측 상수로 착각하고 조정해도 아무 변화가 없는 함정이었다.)

// 날개 폭 테이퍼 — 웨이크버니 실측
//   깊은 날개(패널2) 끝 폭:  A 46.0→25.6  B 36.0→15.6
//   한쪽 인셋으로 환산하면 A (46−25.6)/2 = 10.2,  B (36−15.6)/2 = 10.2
//   ⟹ 비율이 아니라 **한쪽 10.2mm 고정**이다 (두 케이스 완전 일치)
//   얕은 날개는 사선 기울기 dx/dy ≈ 0.30 (A 0.284 / B 0.32) 로 좁아진다
//   ⟹ 인셋 = min(10.2, 0.30·깊이, 패널폭·0.30)
// 위 띠(작은 띠)도 강하게 테이퍼된다 — 웨이크버니 y레벨 절단 실측
//   B 위 띠 28.0mm:  접는선 [15.0-50.4] 거의 전폭
//                    70%   [17.1-32.5][34.6-48.6]  ← 가운데 슬릿으로 갈라짐
//                    100%  [17.9-23.2][42.5-48.0]  ← 혀 폭 5.4mm 씩 2개
//   끝단 재료가 패널당 10.8mm 뿐이고 A(46mm 패널)도 10.8mm — **상수**다.
//   두 혀 사이 슬릿은 메워서(보수적으로) 사다리꼴 하나로 근사한다.
export const TIP_W = 10.8;
export const TAPER_MAX = 10.2, TAPER_SLOPE = 0.30, FULL_FRAC = 0.7;

/**
 * 「이 날개는 끝까지 패널 폭 그대로」 — 테이퍼 없음.
 *
 * ★ 26-08-19 — 맞뚜껑 텍 혀가 여기 해당한다는 것이 **실측으로 확정**됐다.
 *   추출기가 혀를 독립 성분으로 떼어 낸 값(verify-pdf §A CASES 주석에 이미 있던 숫자):
 *     바이오머   혀 **148.6** × 15.0   (패널 W 150 → 인셋 한쪽 0.7)
 *     더파이러츠 혀 **188.6** × 18.0   (패널 W 190 → 인셋 한쪽 0.7)
 *   즉 텍 혀는 패널 폭에서 슬릿 0.7mm 만 좁다. 그런데 종전 모델은 tipW=null 의
 *   사선 기울기형을 태워 한쪽 **9.9mm** 를 깎았다(min(10.2, 0.3h, 0.3pw)).
 *   그 9.2mm 부족이 모델을 실물보다 작게 만든다.
 *   ⚠ 26-08-19 정정 — 종전 여기 적혀 있던 「실물 겹침 15.58mm²」는 **재현되지 않는다.**
 *     tipW 만 null 로 되돌려 돌리면 실물 겹침은 바이오머·더파이러츠 둘 다 0.00mm²
 *     (114조합 신규 0건)이다. 이 상수를 지키는 것은 겹침이 아니라 **커버리지 게이트**다
 *     (바이오머 부족 553.0mm² · 더파이러츠 391.4mm² 로 ★신규 → EXIT=1).
 *     측정 조건과 되돌림 A/B 는 tuck-both.mjs flaps() 의 같은 날짜 주석이 소유한다.
 *   ⚠ 「사다리꼴 근사는 보수적」이라는 아래 addFlap 주석은 **슬릿을 메우는 쪽**에만
 *     맞는 말이고 **사선 측면에는 안 맞는다.** 사선은 재료를 깎아내므로 부족 방향이다.
 */
export const TIP_FULL = Infinity;

/**
 * 패널 x 경계 — 세로 크리스 직접 실측 (웨이크A·웨이크B·도솔 6/6 경계 잔차 0.00mm)
 *   패널 폭 = [D−0.70, W, D, W, 15.00]   (탭은 오른쪽 끝, 마지막 항)
 *
 * ★ 종전 [D, W, D, W, 14.3] 은 내부 접는선 4개가 전부 +0.70mm 어긋나 있었다.
 *   왜 안 들켰나 — 유일한 픽스처가 바이오머 150×15×150 이었고 D=15 가 탭 폭 15.0 과
 *   같아서 두 프레임이 「같은 값들의 순열」이 되어 오차 0.0mm 로 보였다.
 *   D≠15 인 표본(웨이크A·웨이크B·도솔)에서는 즉시 0.70mm 가 드러난다.
 *
 * ⚠ D < 0.7 (실물에 없는 극박)에서 음수 폭이 나지 않게 clamp 한다. clamp 가 걸리면
 *   부족분이 탭으로 흡수되므로(탭 = D + 14.3 − d0) 단조성과 netW 는 그대로 지켜진다.
 */
export const xEdges = (W, D, netW) => {
  const d0 = Math.max(0, D - GLUE_TAB_SHORT);
  return [0, d0, d0 + W, d0 + W + D, d0 + 2 * W + D, netW];
};

/**
 * 위 xEdges 가 가정하는 패널 이름. 화면이 이 배열을 따로 갖지 않게 여기서 내보낸다.
 *
 * ★ 실측 도면 ↔ 우리 프레임 인덱스 사상 (이것만 외우면 된다)
 *   고객사 칼선 PDF 6/6 은 접착탭이 **왼쪽**이고 순서가 [탭 15][W][D][W][D−0.7] 이다.
 *   우리 xEdges 는 그 **좌우 거울상** [D−0.7][W][D][W][탭 15] 이다.
 *       실측 [탭, W1, D1, W2, D2]  ↔  현행 [4, 3, 2, 1, 0]
 *   패널 **타입** 순서가 정확히 일치하므로 현행은 같은 목형을 뒤에서 본 그림이고,
 *   좌우 반전은 인쇄판 반전과 같아 물리적으로 동일한 목형이다. 반전하지 않는 근거는
 *   glue3.mjs 「좌우 반전을 안 하는 이유」 참조.
 */
export const PANEL_LABELS = ["측면1", "전면", "측면2", "후면", "접착"];

export const rect = (x0, y0, x1, y1) => [[x0, y0], [x1, y0], [x1, y1], [x0, y1]];

/**
 * 전개도를 **볼록 조각의 합집합**으로 만든다. NFP 배치와 화면 그림이 이걸 함께 쓴다.
 * 조각이 전부 볼록이라 다각형 불리언 없이 정확한 민코프스키 합이 가능하다.
 *
 * ⚠ 이 함수는 xEdges 의 「몸통4 + 접착탭1」 슬리브 위상만 만든다. 다른 위상
 *   (사각트레이 netW = W+2H+24 처럼 netW 가 2(W+D) 계열이 아닌 구조)을 넣으면
 *   xEdges 가 netW 를 넘어 단조성이 깨진다 — 그래서 아래에서 즉시 null 을 낸다.
 *   그런 구조는 자기 파일에 pieces(W,D,H,{net,flaps,opt}) 훅을 선언하면 된다
 *   (dieline/index.mjs dielinePieces 참조).
 *
 * 날개 2단 분리:
 *   테이퍼가 있으면 [전폭 0~70%] + [사다리꼴 70~100%] 두 조각으로 쪼갠다.
 *   좁은 혀 옆의 빈 공간이 맞물림 공간이다. 한 덩어리로 그리면 그 공간이 사라진다.
 *
 * cuts/folds 를 **같은 루프에서** 낸다 — 화면이 배치와 다른 도형을 그리는 일을
 * 구조적으로 불가능하게 만드는 것이 이 파일의 존재 이유다.
 * @returns {{pieces, meta, cuts, folds, panels}|null}
 *   pieces = 볼록 4~6각형(배치 입력) / meta = 조각별 패널 번호·역할(색칠용)
 *   cuts   = 칼선 폴리라인(열린 선)   / folds = 접는선 2점 선분
 *   panels = [{i,x0,x1,label}] 패널 경계 — 화면이 xEdges 를 다시 계산하지 않게
 */
export function piecesFromFlaps({ W, D, H, net, flaps, opt = {} }) {
  const taper = opt.taper !== false;
  const y0 = net.topLid, y1 = net.topLid + H;
  const xE = xEdges(W, D, net.netW);
  // 위상 검사 — 단조증가가 깨지면 이 함수가 만들 수 있는 도형이 아니다.
  // 조용히 음수 폭 패널을 만들면 bbox 가 netW 와 수백 mm 어긋난 채 배치까지 흘러간다.
  for (let i = 1; i < xE.length; i++) if (xE[i] < xE[i - 1] - 0.05) return null;
  const pieces = [], meta = [], cuts = [], folds = [];
  const topOf = i => flaps.top?.[i] ?? 0;
  const botOf = i => flaps.bot?.[i] ?? 0;

  const addFlap = (panel, x0, x1, base, h, dir, tipW) => {
    if (h <= 0.05) return;
    const pw = x1 - x0;
    // tipW = TIP_FULL(Infinity) 이면 인셋 0 → 전폭 사각형. 「테이퍼 없음」을 값으로 말한다.
    const ins = tipW != null
      ? Math.max(0, (pw - tipW) / 2)                       // 끝단 폭 고정형 (위 띠)
      : Math.min(TAPER_MAX, TAPER_SLOPE * h, pw * 0.30);   // 사선 기울기형 (아래 띠)
    const part = dir < 0 ? "flapTop" : "flapBot";
    if (!taper || ins <= 0.05) {                    // 테이퍼 없음 = 종전 전폭 사각형
      const yT = base + dir * h;
      pieces.push([[x0, base], [x0, yT], [x1, yT], [x1, base]]);
      meta.push({ panel, part });
      cuts.push([[x0, base], [x0, yT], [x1, yT], [x1, base]]);
      return;
    }
    // 실측은 깊이 70% 까지 전폭을 유지하다 끝에서 급히 좁아진다.
    // 밑변부터 선형으로 좁히면 중간이 실물보다 얇아져 up 을 과대평가한다 →
    // 안전측으로 [전폭 0~70%] + [사다리꼴 70~100%] 두 조각으로 나눈다.
    const yF = base + dir * h * FULL_FRAC, yT = base + dir * h;
    pieces.push([[x0, base], [x0, yF], [x1, yF], [x1, base]]);
    meta.push({ panel, part });
    pieces.push([[x0, yF], [x0 + ins, yT], [x1 - ins, yT], [x1, yF]]);
    meta.push({ panel, part });
    // 칼선은 두 조각의 **외곽만** 따라간다. yF 의 이음선은 칼도 접는선도 아니다
    // (조각 분할은 볼록성을 얻기 위한 계산상의 편의일 뿐 실물에 없는 선이다).
    cuts.push([[x0, base], [x0, yF], [x0 + ins, yT], [x1 - ins, yT], [x1, yF], [x1, base]]);
  };

  for (let i = 0; i < 5; i++) {
    const x0 = xE[i], x1 = xE[i + 1], pw = x1 - x0;
    if (pw <= 0.05) continue;
    if (i === 4) {
      // 접착탭 — **직사각형**으로 그린다 (26-08-19 정정)
      //
      // 종전에는 위아래를 tc = min(pw·0.55, H·0.12, 8) 만큼 깎은 쐐기였다. 실물 탭이
      // 모따기된 것은 사실이다(소스코 실측: 아래쪽 대각 (31.69,211.47)→(16.69,207.45)
      // ≈ 4mm, 위쪽 곡선 (16.69,97.66)→(22.69,87.27) ≈ 10mm). **그런데 tc 공식 자체에는
      // 실측 근거가 없었다** — 세 항 어디에도 출처 주석이 없다. 근거 없는 상수가
      // 도형을 **깎는** 방향으로 쓰이면 그건 up 과대(=영업 위험)다.
      //   실제로 잡혔다: 바이오머 150×15×150 @4×64 2up 1×2(반피치 엇갈·반전)에서
      //   원본 칼선 PDF 기준 실물 겹침 **12.35mm²**. tc=0 으로 두면 **0.00mm²**.
      //   (게이트: verify-imposition 「실물 겹침」. 모델 재측정 자기검사②는 0 이므로
      //    계측기 잡음이 아니라 모델이 실물을 못 덮은 것이다.)
      //   ★ 재현 조건 (26-08-19 재실행 · 이 숫자는 **재현된다**): 이 작업트리에서
      //     위 tc 3줄만 되살리고 `node test/verify-imposition.mjs` →
      //     「✗ 바이오머 최대 12.35mm² @4x64 2up 1×2 ★신규」 · 114조합 신규 겹침 1건 ·
      //     EXIT=1. 커버리지 게이트도 같이 잡는다(소스코 10.24mm/967mm²).
      //     ⚠ 자매 항목인 맞뚜껑 tipW 쪽 「15.58mm²」는 반대로 **재현되지 않았다** —
      //       두 변경을 한 근거로 묶어 읽지 마라(위 TIP_FULL 주석 참조).
      // ⟹ 모따기 양을 실측으로 특정하기 전까지는 **안 깎는다.** 근거 없는 상수는
      //   「크게 그려라」 쪽으로 정한다는 이 저장소의 정책 그대로다.
      //   되살리려면 목형별 모따기를 실측해서 상한을 잡아라(현재 표본 1벌, 4~10mm).
      pieces.push([[x0, y0], [x1, y0], [x1, y1], [x0, y1]]);
      meta.push({ panel: 4, part: "tab" });
      cuts.push([[x0, y0], [x1, y0], [x1, y1], [x0, y1]]);
      continue;
    }
    pieces.push([[x0, y0], [x1, y0], [x1, y1], [x0, y1]]);   // 몸통
    meta.push({ panel: i, part: "body" });
    addFlap(i, x0, x1, y0, topOf(i), -1, flaps.tipW ?? null);
    addFlap(i, x0, x1, y1, botOf(i), +1);
    // 날개가 없는 구간의 몸통 위/아래 경계는 접는선이 아니라 칼선이다
    if (topOf(i) <= 0.05) cuts.push([[x0, y0], [x1, y0]]);
    if (botOf(i) <= 0.05) cuts.push([[x0, y1], [x1, y1]]);
  }

  // 패널 사이 접는선 — 날개가 있는 쪽은 양쪽 날개가 겹치는 깊이까지만 이어진다
  for (let i = 1; i <= 4; i++) {
    if (xE[i + 1] - xE[i] <= 0.05) continue;
    const yA = y0 - Math.min(topOf(i - 1), topOf(i));
    const yB = y1 + Math.min(botOf(i - 1), botOf(i));
    folds.push([[xE[i], yA], [xE[i], yB]]);
  }
  // 몸통 상·하 접는선 (날개가 붙은 구간만)
  for (const [y, of_] of [[y0, topOf], [y1, botOf]]) {
    for (let i = 0; i < 4; i++) {
      if (of_(i) > 0.05) folds.push([[xE[i], y], [xE[i + 1], y]]);
    }
  }
  // 좌측 최외곽 칼선 (패널0 왼쪽)
  cuts.push([[0, y0], [0, y1]]);

  const panels = PANEL_LABELS.map((label, i) => ({ i, x0: xE[i], x1: xE[i + 1], label }))
                             .filter(p => p.x1 - p.x0 > 0.05);
  return { pieces, meta, cuts, folds, panels };
}
