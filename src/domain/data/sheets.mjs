/** 1R(1연) 장수 = 500 × 절수 */
export const sheetsPerR = sheet => 500 * (sheet?.cut || 2);

/**
 * 판형 크기 구간 — 코팅·톰슨·인쇄 단가 티어를 결정한다.
 * 값은 **절수 이름 그대로**다. 종전 'small'|'mid'|'large' 는 견적서·실무가 쓰는
 * 「4절/2절/전지」라는 도메인 뜻을 지워서, tier:'large' 만 보고는 전지급이라는 걸
 * 알 수 없었다. COAT_OPTS·THOMSON_OPTS·RANK_* 의 컬럼명도 같은 키를 쓴다.
 * ※ "2절" 티어는 2절과 3절을 **함께** 덮는다 (단가가 같다).
 */
export const TIERS = ["4절", "2절", "전지"];

export function sheetTier(sheet) {
  if (!sheet) return "2절";
  if (sheet.cut >= 4) return "4절";
  if (sheet.cut === 1) return "전지";
  return "2절";
}

/** 판형 ∩ 인쇄기 최대 → 실제 인쇄 가능한 판 크기 (긴변, 짧은변) */
export function effectiveSheet(sw, sh) {
  const long  = Math.min(Math.max(sw, sh), PRESS_MAX_LONG);
  const short = Math.min(Math.min(sw, sh), PRESS_MAX_SHORT);
  return { long, short, capped: long < Math.max(sw, sh) || short < Math.min(sw, sh) };
}

export const findSheetBase = id => BASE_SHEETS.find(s => s.id === id) || null;

/** 주문생산이면 사용자 입력 크기·절수로 덮어쓴다.
 *  종전에는 같은 삼항이 App.jsx 5곳에 흩어져 있었다 — 한 곳이라도 빠지면
 *  주문생산 판형이 890×670 기본값으로 조용히 계산된다. */
export const resolveSheet = (base, customSheet) =>
  (base?.custom && customSheet) ? { ...base, ...customSheet } : base;
