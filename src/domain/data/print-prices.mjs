//        1R 별3 130,500 → 50,000 (−80,500)   ·   4R 별3  522,000 → 200,000 (−322,000)
//     내리면 회사가 손해다. 개별 근거 없이 다수결로 내리지 않는다(GLUE_MIN_LOT 선례).
//
//  ② ★ 더 중요한 것 — **그 34건은 「단위가 다른 것」이 아니라 위 「답 1」의 B형(판당 정액)이다.**
//     R1(협상 1표)·R5(접착 단상자)로 세면 별색 표본은 **9협상**뿐이고, 그 원문이 이렇다:
//        25-11-21 카드패키지   40,000 × 수량칸 1      «별1»
//        25-12-08 덴탈맥스     45,000 × 수량칸 10     «먹+별1»
//        25-12-15 도솔메디     14,000 × 수량칸 7      «4도+별1»   ← ①(도수환산) 그대로다
//        26-03-18 바이오머테리얼즈 60,000 × 수량칸 1    «별1+먹»
//        26-03-27 에코유어스킨   50,000 × 수량칸 2      «전면별2/후면원색4»
//        26-05-26 선인장한의원   14,000 × 수량칸 6      «별2»      ← ①(도수환산) 그대로다
//        26-07-31 웨이크버니    42,000 × 수량칸 10.2   «별2+먹1 / 별1»
//        26-09-09 겟뷰티       45,000 × 수량칸 1.7    «별1+먹»
//     수량칸이 1 · 1.7 · 2 · 6 · 7 · 10 · 10.2 로 **제각각이다.** 「R당 고정」이라면 수량칸이
//     그 문서의 공정R 이어야 하는데 1 과 10 이 같이 나온다 — 즉 **R 의 함수가 아니다.**
//     이것은 「답 2」가 이미 반증한 것과 같은 물건이다: B형 단가는 도수·R 의 함수가 아니라
//     **건별 협의 정액**이고, 실효 도당단가가 6배 흩어진다. 식으로 옮길 수 없다.
//  ⟹ 기본 ① 유지. 별색 건의 오차(±10% 47.4%)는 **단가표의 잘못이 아니라 협의가**다.
//    화면의 별색 모드 선택과 spotRpr 직접입력이 그 자리를 메우는 설계다(PrintPanel).
export const SPOT_WEIGHT      = 3;      // 별색 1도 = 인쇄 3회
export const SPOT_RPR_PLAIN   = 50000;  // ② 별색 전용 R단가 (일반)
export const SPOT_RPR_BEDA    = 75000;  // ② 별색 전용 R단가 (베다/바탕)

// ── 한 면의 도수 세는 법 ───────────────────────────────────────────
// 원색(CMYK 4도)·별색·먹은 **서로 병행 가능**하다 (원색4 + 별색2 = 6도).
// 이 두 줄이 종전에 4곳(도수 표시·소부·여분 판단·인쇄비)에 각각 적혀 있었고,
// 그래서 "원색+별색 병행" 을 고칠 때 한 곳을 빠뜨리는 사고가 반복됐다.
// SPOT_WEIGHT 를 어디에 곱하는지가 두 함수의 유일한 차이라서 여기 나란히 둔다.

/** 소부·표시용 총 도수 — 별색도 1도로 센다 (판 수는 별색도 1장) */
export const sideColors = sd => (sd.color ? 4 : 0) + (sd.spot || 0) + (sd.black ? 1 : 0);

/** 인쇄비용 "가중치 1" 도수 — 원색·먹만. 별색은 SPOT_WEIGHT 가 따로 붙는다 */
export const sideFlat = sd => (sd.color ? 4 : 0) + (sd.black ? 1 : 0);

// ── ★ 26-09-15 소부 판수 — 「UV 는 소부가 없다」를 코퍼스가 반증했다 ──────────
//  종전 주장(이 파일과 process/soboo.mjs 에 같이 적혀 있었다):
//    「UV인쇄는 별도 UV기계라 소부 없음 (견적서 전건 확인)」
//  전 코퍼스 853레코드로 다시 세면 **정반대다.** UV 인쇄 줄이 있는 레코드 18건,
//  그 **18건 전부**가 소부 줄을 따로 갖고 있다 (11,000 / 12,000 / 22,000×11 /
//  44,000×4 / 55,000 — 중앙 22,000원). 0원짜리는 한 건도 없다.
//
//  ★ 더 중요한 것은 **소부 수량칸이 무엇을 세고 있었나**다. 그 18건의 소부 규격칸을
//    읽으면 수량이 정확히 잉크 판수다:
//      «4도»→4 (3건) · «4도별1»→5 · «별2»→2 (4건) · «별1»→1 · «양면 먹1»→2
//    ⟹ UV 는 **잉크 종류**(UV경화 잉크)이지 「판이 없다」는 뜻이 아니었다. UV 오프셋도
//      판을 태운다. 종전 주장은 UV 줄의 금액이 도수와 무관하다(uvAmount 티어)는
//      사실을 「그러니 판도 없다」로 **한 칸 더 밀어 읽은 것**이다.
//
//  그래서 도수 함수를 갈아엎지 않고 **바닥만 올린다**: 잉크 구성을 사용자가 적어 뒀으면
//  그 판수가 맞고(엔진은 이미 그렇게 세고 있었다), UV 만 적혀 구성이 비면 그래도 1판이다.
//  ⚠ 방향이 **위**다 — 0 을 1 로 올릴 뿐 기존 값을 한 번도 안 내린다(단조). 위험 방향
//    규율(비싼 쪽)과 같은 쪽이고, 절대선(소스코 = 원색4·UV아님)에는 닿지 않는다.
/** 소부 **판수** — UV 만 적힌 면도 판은 태운다(최소 1판). 코퍼스 18/18 근거는 위 주석 */
export const sidePlates = sd => Math.max(sideColors(sd), sd.uv ? 1 : 0);

/**
 * UV인쇄: 도수 무관 수량 티어 고정가 (별도 UV기계 — 다만 **소부는 있다**, sidePlates 주석)
 *   ✓ 47×47×176 5,000ea → 250,000 / 10,000ea → 350,000 / UV건 1,000ea → 200,000
 *
 * ⚠ 못 고친 것 — 이 티어는 **정액**인데 코퍼스는 UV 를 R 로도 청구한다:
 *   25-10-13 10×30,000 · 25-11-10 4×200,000 · 26-01-28 10×30,000 (수량칸이 1 이 아니다).
 *   18건 중 6건이 그렇다. 정액/R 을 가르는 축이 사양에 없어(같은 3,000ea 가 1×250,000 과
 *   4×200,000 둘 다 나온다) **지금 표본으로는 규칙을 못 세운다.** 세우면 지어내는 것이다.
 */
export function uvAmount(qty) {
  if (qty <=  3000) return 200000;
  if (qty <=  5000) return 250000;
  if (qty <= 10000) return 350000;
  return Math.round(qty / 1000 * 35000);
}
