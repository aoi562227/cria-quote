//   ② R당 고정 : 별색 전용 단가를 R에 곱하기
//        십자B 별2 50,000/R · 조립형 별1 50,000~65,000/R
//        G형 별1베다+먹 75,000/R  ·  G형C 별1베다+먹 76,190/R ✓ (독립 2건 일치)
// → 기본은 ①(대조 견적서 근거). 베다(바탕 전면 인쇄)는 R당 실효금액이
