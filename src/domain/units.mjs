// Math.round 는 감싸지 않는다 — 래퍼가 늘면 반올림 위치를 grep 으로 못 찾는다.
// 여기 두 개는 "왜 0.1 인가 / 왜 3자리인가" 가 실측 근거와 묶여 있어서 이름이 필요하다.

/** 0.1 단위 올림 — 전지급 지대R(=50장 묶음) · 공정R 공용 */
export const ceil1 = v => Math.ceil(v * 10) / 10;

/** 소수 3자리 올림 — 2절 이하 지대R */
export const ceil3 = v => Math.ceil(v * 1000) / 1000;
