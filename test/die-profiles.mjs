const keyOf = (t, W, D, H) => `${t}|${W}|${D}|${H}`;

/** 그 목형의 구조 옵션. 표에 없으면 **빈 객체**(= 기본 봉투로 계산). */
export const dieOptOf = (t, W, D, H) => T[keyOf(t, W, D, H)]?.opt ?? {};

/** 실린 노브의 출처 라벨. "" = 노브가 안 실렸다(미실측·미등록·의도적 공백).
 *  ⚠ `src` 를 그대로 돌려준다 — "미실측" 인데 opt 가 차 있으면 **"미실측" 이 찍힌다.**
 *  그게 맞다: 그 상태는 정상이 아니고 표에 그대로 보여야 한다(verify-imposition
 *  「추정 되먹임 금지」 ①이 같은 조건으로 exit 1 을 낸다). 여기서 "" 로 감추지 마라. */
export const dieSrcOf = (t, W, D, H) => {
  const e = T[keyOf(t, W, D, H)];
  return e && Object.keys(e.opt).length ? e.src : "";
};

/**
 * ★ 이 케이스가 **점수로 셀 수 있는가**.
 *   false = 원본 도면이 없어 노브를 못 채운 건(미실측). 「목형 지정」 열에서 이 건이
 *   견적서와 어긋나는 것은 모델의 실패가 아니라 **자료의 부재**다 — 그래서 점수표는
 *   이 건을 분리 집계하고 대표 숫자는 「실측 전용」을 쓴다.
 *   ⚠ 「점수 아님」은 면죄부가 아니다: 분모에서 빼는 대신 몇 건인지 항상 찍는다.
 */
export const dieScorable = (t, W, D, H) => T[keyOf(t, W, D, H)]?.src !== "미실측";

/** 점수판 각주용 한 줄 요약 — 「추정이 몇 건 섞였나」를 숨기지 않는다. */
export function dieNote(cases) {
  let meas = 0, est = 0, unk = 0;
  for (const [t, W, D, H] of cases) {
    const s = dieSrcOf(t, W, D, H);
    if (s === "실측") meas++; else if (s === "추정") est++;
    if (!dieScorable(t, W, D, H)) unk++;
  }
  return `목형 지정 ${meas + est}건 (실측 ${meas} · 추정 ${est})` +
         (unk ? ` · 미실측 ${unk}건은 기본 봉투로 계산 = **점수 아님**(원본 도면 확보 전)` : "") +
         (est ? ` — ⚠ 추정 ${est}건은 견적서 up 에서 역으로 정한 값이라 그만큼은 순환이다` : "");
}

/**
 * 「실측만으로 몇 점인가」 — 점수판의 **대표 숫자**.
 * rows = [{name, ok, t, W, D, H}]. 미실측 건은 분모에서 빼고 따로 센다.
 * @returns {{hit,tot,skip,text}}
 */
export function measuredOnly(rows) {
  let hit = 0, tot = 0, skip = 0, miss = [];
  for (const r of rows) {
    if (!dieScorable(r.t, r.W, r.D, r.H)) { skip++; if (!r.ok) miss.push(r.name); continue; }
    tot++; if (r.ok) hit++;
  }
  return { hit, tot, skip,
    // ★ 「★」와 「← 대표 숫자」를 **텍스트 안에** 넣는다. 네 스위트가 각자 붙이면
    //   한 곳이 빠져도 아무도 모르고, 그러면 그 표만 부풀린 「목형 지정」 열이
    //   헤드라인으로 읽힌다(이번 사고가 정확히 그 모양이었다).
    text: `★ 실측 전용 점수 ${hit}/${tot}` +
          (skip ? `  (미실측 ${skip}건 제외${miss.length ? ` — 그중 ${miss.length}건이 견적서와 불일치: ${miss.join(" · ")}` : ""})` : "") +
          `  ← 대표 숫자` };
}

